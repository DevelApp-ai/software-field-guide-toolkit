using System.Text;

namespace Sfg.Toolkit.DrillHarness;

/// <summary>
/// Renders the drill evidence board (#81): drills.md (the human board) and
/// drills.json (the machine summary). All deterministic: sorted, no
/// timestamps, byte-identical on regeneration. There is no baseline file —
/// the drill export is itself the record; freshness is judged against the
/// recorded asOf instant, never the wall clock.
/// </summary>
public static class DrillHarnessRenderer
{
    public const string Generator = "sfg drills 0.11.0";

    public static string Markdown(DrillHarnessConfig config, DrillReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Drill evidence board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — suite **{config.Name}**, drill **{report.Drill}**, judge `{config.Judge}`, asOf {report.AsOf:yyyy-MM-dd}.");
        builder.AppendLine();
        builder.AppendLine("Honest status: `sfg drills` judges recorded drill evidence — it never injects failures. A drill that happened once and left no record is indistinguishable from a rehearsal that never happened.");
        builder.AppendLine();

        builder.AppendLine("## Scenario freshness");
        builder.AppendLine();
        builder.AppendLine("| Scenario | Title | Last drilled | Age (days) | Window (days) | Status |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- |");
        foreach (var row in report.Freshness)
        {
            builder.AppendLine($"| `{row.Scenario}` | {row.Title} | {(row.LastDrilled is null ? "—" : row.LastDrilled.Value.ToString("yyyy-MM-dd"))} | " +
                               $"{(row.AgeDays is null ? "—" : row.AgeDays.Value.ToString("0"))} | {row.StalenessDays} | {row.Status} |");
        }

        builder.AppendLine();
        builder.AppendLine($"Staleness is measured against the recorded asOf instant ({report.AsOf:yyyy-MM-dd}), never the wall clock — the analysis is deterministic.");
        builder.AppendLine();

        builder.AppendLine("## Clocks");
        builder.AppendLine();
        if (report.Clocks.Count == 0)
        {
            builder.AppendLine("No drill record in this export — no clock was exercised.");
        }
        else
        {
            builder.AppendLine("| Scenario | Alert (s) | Alert clock | Restore (s) | RTO | Loss window (s) | RPO | Verdict |");
            builder.AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- |");
            foreach (var row in report.Clocks)
            {
                builder.AppendLine($"| `{row.Scenario}` | {Cell(row.AlertSeconds)} | {Num(row.AlertClock)} | " +
                                   $"{Cell(row.RestoreSeconds)} | {Num(row.RtoClock)} | {Cell(row.RpoSeconds)} | {Num(row.RpoClock)} | {row.Verdict} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Signals");
        builder.AppendLine();
        if (report.Signals.Count == 0)
        {
            builder.AppendLine("No drill record in this export — no signal was recorded.");
        }
        else
        {
            builder.AppendLine("| Scenario | Missing expected signals | Evidence |");
            builder.AppendLine("| --- | --- | --- |");
            foreach (var row in report.Signals)
            {
                var missing = row.Missing.Count == 0 ? "—" : string.Join(", ", row.Missing.Select(key => $"`{key}`"));
                builder.AppendLine($"| `{row.Scenario}` | {missing} | `{row.Anchor}` |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Participation");
        builder.AppendLine();
        if (report.Participation.Count == 0)
        {
            builder.AppendLine("No drill record in this export — nobody is on the record.");
        }
        else
        {
            builder.AppendLine("| Scenario | Participants | Versions | Verdict |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var row in report.Participation)
            {
                var participants = row.Participants.Count == 0 ? "—" : string.Join(", ", row.Participants);
                var versions = row.Versions.Count == 0 ? "—" : string.Join(", ", row.Versions.Select(v => $"`{v}`"));
                builder.AppendLine($"| `{row.Scenario}` | {participants} | {versions} | {row.Verdict} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Clean run: every scenario is drilled fresh, every alert fired inside its clock, every restore met its RTO, every RPO held, the expected signals are on the record, and participants and versions are named.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Evidence |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var evidence = finding.Evidence.Count == 0
                    ? "—"
                    : string.Join(" · ", finding.Evidence.Select(e => $"`{e}`"));
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {evidence} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Freshness.Count} scenario(s), {report.Clocks.Count} drill record(s), " +
                           $"{report.Findings.Count} finding(s) — {report.Errors} error(s), {report.Warnings} warning(s). " +
                           "Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(DrillHarnessConfig config, DrillReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"suite\": {J(config.Name)},");
        builder.AppendLine($"  \"drill\": {J(report.Drill)},");
        builder.AppendLine($"  \"judge\": {J(config.Judge)},");
        builder.AppendLine($"  \"asOf\": {J(report.AsOf.UtcDateTime.ToString("yyyy-MM-ddTHH:mm:ss'Z'", System.Globalization.CultureInfo.InvariantCulture))},");
        builder.AppendLine($"  \"stalenessDays\": {report.StalenessDays},");
        builder.AppendLine("  \"freshness\": {");
        for (var i = 0; i < report.Freshness.Count; i++)
        {
            var row = report.Freshness[i];
            var comma = i < report.Freshness.Count - 1 ? "," : string.Empty;
            var lastDrilled = row.LastDrilled is null
                ? "null"
                : J(row.LastDrilled.Value.ToString("yyyy-MM-dd"));
            var ageDays = row.AgeDays is null ? "null" : row.AgeDays.Value.ToString("0");
            builder.AppendLine($"    {J(row.Scenario)}: {{ \"lastDrilled\": {lastDrilled}, \"ageDays\": {ageDays}, " +
                               $"\"stalenessDays\": {row.StalenessDays}, \"status\": {J(row.Status)} }}{comma}");
        }

        builder.AppendLine("  },");
        builder.AppendLine("  \"clocks\": [");
        for (var i = 0; i < report.Clocks.Count; i++)
        {
            var row = report.Clocks[i];
            var comma = i < report.Clocks.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"scenario\": {J(row.Scenario)}, \"alertSeconds\": {JsonNum(row.AlertSeconds)}, " +
                               $"\"alertClock\": {Num(row.AlertClock)}, \"restoreSeconds\": {JsonNum(row.RestoreSeconds)}, " +
                               $"\"rto\": {Num(row.RtoClock)}, \"rpoSeconds\": {JsonNum(row.RpoSeconds)}, " +
                               $"\"rpo\": {Num(row.RpoClock)}, \"verdict\": {J(row.Verdict)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"signals\": [");
        for (var i = 0; i < report.Signals.Count; i++)
        {
            var row = report.Signals[i];
            var comma = i < report.Signals.Count - 1 ? "," : string.Empty;
            var missing = string.Join(", ", row.Missing.Select(J));
            builder.AppendLine($"    {{ \"scenario\": {J(row.Scenario)}, \"missing\": [{missing}], \"anchor\": {J(row.Anchor)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"participation\": [");
        for (var i = 0; i < report.Participation.Count; i++)
        {
            var row = report.Participation[i];
            var comma = i < report.Participation.Count - 1 ? "," : string.Empty;
            var participants = string.Join(", ", row.Participants.Select(J));
            var versions = string.Join(", ", row.Versions.Select(J));
            builder.AppendLine($"    {{ \"scenario\": {J(row.Scenario)}, \"participants\": [{participants}], " +
                               $"\"versions\": [{versions}], \"verdict\": {J(row.Verdict)}, \"anchor\": {J(row.Anchor)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.RenderedFindings.Count; i++)
        {
            var finding = report.RenderedFindings[i];
            var comma = i < report.RenderedFindings.Count - 1 ? "," : string.Empty;
            var evidence = string.Join(", ", finding.Evidence.Select(J));
            builder.AppendLine($"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, " +
                               $"\"message\": {J(finding.Message)}, \"evidence\": [{evidence}] }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Cell(double? value) => value is null ? "—" : Num(value.Value);

    private static string JsonNum(double? value) => value is null ? "null" : Num(value.Value);

    internal static string Num(double value) =>
        value.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture);

    internal static string J(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }
}
