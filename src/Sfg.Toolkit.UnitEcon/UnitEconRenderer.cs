using System.Text;

namespace Sfg.Toolkit.UnitEcon;

/// <summary>
/// Renders the cloud unit-economics board (#83): unit-econ.md (the human
/// board) and unit-econ.json (the machine summary). All deterministic:
/// sorted, no timestamps, byte-identical on regeneration. The honesty line is
/// always on the board — a seeded estate must say it is seeded, a real one
/// must say its numbers are recorded exports; `sfg unit-econ` never calls a
/// live cloud API.
/// </summary>
public static class UnitEconRenderer
{
    public const string Generator = "sfg unit-econ 0.12.0";

    public static string Markdown(UnitEconConfig config, UnitEconReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Cloud unit economics board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — estate **{config.Name}**, billing export `{report.Export}`, allocation manifest `{report.Manifest}`, telemetry source `{report.Source}`, currency {config.Currency}, granularity {config.Granularity}.");
        builder.AppendLine();
        builder.AppendLine(config.Seeded
            ? "**SEEDED estate — no real billing history backs these numbers; they demonstrate the joins, not a cloud bill.** `sfg unit-econ` reads recorded exports and never calls a live cloud API."
            : "Recorded exports only — `sfg unit-econ` never calls a live cloud API; the numbers are as recorded, the joins are as verified.");
        builder.AppendLine();

        builder.AppendLine("## Tenant spend");
        builder.AppendLine();
        builder.AppendLine("| Tenant | Period | Spend | Budget | Status |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var row in report.Spend)
        {
            var budget = row.Budget is null ? "—" : Money(row.Budget.Value);
            builder.AppendLine($"| `{row.Tenant}` | {row.Period} | {Money(row.Spend)} | {budget} | {row.Status} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Cost per request");
        builder.AppendLine();
        builder.AppendLine("| Tenant | Service | Period | Allocated cost | Requests | Cost per request |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- |");
        foreach (var row in report.CostPerRequest)
        {
            var unit = row.CostPerRequest is null ? "—" : Num(row.CostPerRequest.Value);
            builder.AppendLine($"| `{row.Tenant}` | `{row.Service}` | {row.Period} | {Money(row.AllocatedCost)} | {row.Requests} | {unit} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Clean run: every billed service is allocated, every served request is priced, every join verified, and every tenant is inside its budget.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Evidence |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var evidence = finding.Evidence.Count == 0
                    ? "—"
                    : string.Join(" · ", finding.Evidence.Select(e => $"`{e}`"));
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {evidence} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Tenants} tenant(s), {report.Services} service(s), {report.Periods} period(s), " +
                           $"{report.Spend.Count} spend row(s), {report.CostPerRequest.Count} cost-per-request row(s), " +
                           $"{report.Findings.Count} finding(s) — {report.Errors} error(s), {report.Warnings} warning(s). " +
                           "Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(UnitEconConfig config, UnitEconReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"estate\": {J(config.Name)},");
        builder.AppendLine($"  \"billingExport\": {J(report.Export)},");
        builder.AppendLine($"  \"allocationManifest\": {J(report.Manifest)},");
        builder.AppendLine($"  \"telemetrySource\": {J(report.Source)},");
        builder.AppendLine($"  \"currency\": {J(config.Currency)},");
        builder.AppendLine($"  \"granularity\": {J(config.Granularity)},");
        builder.AppendLine($"  \"seeded\": {(config.Seeded ? "true" : "false")},");
        builder.AppendLine("  \"spend\": [");
        for (var i = 0; i < report.Spend.Count; i++)
        {
            var row = report.Spend[i];
            var comma = i < report.Spend.Count - 1 ? "," : string.Empty;
            var budget = row.Budget is null ? "null" : Money(row.Budget.Value);
            builder.AppendLine($"    {{ \"tenant\": {J(row.Tenant)}, \"period\": {J(row.Period)}, \"spend\": {Money(row.Spend)}, " +
                               $"\"budget\": {budget}, \"status\": {J(row.Status)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"costPerRequest\": [");
        for (var i = 0; i < report.CostPerRequest.Count; i++)
        {
            var row = report.CostPerRequest[i];
            var comma = i < report.CostPerRequest.Count - 1 ? "," : string.Empty;
            var unit = row.CostPerRequest is null ? "null" : Num(row.CostPerRequest.Value);
            builder.AppendLine($"    {{ \"tenant\": {J(row.Tenant)}, \"service\": {J(row.Service)}, \"period\": {J(row.Period)}, " +
                               $"\"allocatedCost\": {Money(row.AllocatedCost)}, \"requests\": {row.Requests}, \"costPerRequest\": {unit} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.RenderedFindings.Count; i++)
        {
            var finding = report.RenderedFindings[i];
            var comma = i < report.RenderedFindings.Count - 1 ? "," : string.Empty;
            var evidence = string.Join(", ", finding.Evidence.Select(J));
            builder.AppendLine($"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, " +
                               $"\"message\": {J(finding.Message)}, \"evidence\": [{evidence}] }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Money(double value) =>
        value.ToString("0.00", System.Globalization.CultureInfo.InvariantCulture);

    internal static string Num(double value) =>
        value.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture);

    internal static string J(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }
}
