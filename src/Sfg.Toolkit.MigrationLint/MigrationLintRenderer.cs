using System.Text;

namespace Sfg.Toolkit.MigrationLint;

/// <summary>
/// Renders the migration-lint board (#67): migration-lint.md (the human board)
/// and migration-lint.json (the machine summary). Deterministic: ordinal
/// order everywhere, no timestamps of the run, byte-identical on regeneration.
/// </summary>
public static class MigrationLintRenderer
{
    public const string Generator = "sfg migration-lint 0.8.0";

    public static string Markdown(MigrationLintConfig config, MigrationLintReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Migration lint board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — {report.Migrations.Count} migration(s) in `{config.MigrationsDir}/`, " +
                           $"{(report.Gates is null ? $"no gates ledger ({report.GatesName})" : $"{report.Gates.Passes.Count} gate pass(es) in `{report.GatesName}`")}.");
        builder.AppendLine();
        builder.AppendLine("Every statement is classified **expand** (the additive default), **migrate** (rewiring data and " +
                           "readers), or **contract** (removing or tightening) — and every finding cites file:line.");
        builder.AppendLine();

        builder.AppendLine("## Timeline");
        builder.AppendLine();
        builder.AppendLine("| Migration | Date | Expand | Migrate | Contract |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var migration in report.Migrations)
        {
            builder.AppendLine($"| `{migration.FileName}` | {migration.Date:yyyy-MM-dd} | " +
                               $"{migration.Count(MigrationKind.Expand)} | {migration.Count(MigrationKind.Migrate)} | " +
                               $"{migration.Count(MigrationKind.Contract)} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Compatibility windows");
        builder.AppendLine();
        if (report.Gates is null)
        {
            builder.AppendLine($"No gates ledger (`{report.GatesName}`) is committed — legal while the history only expands; " +
                               "the first removal has to record its pass first.");
        }
        else
        {
            builder.AppendLine("| Object | Gate | Expanded | Cold | Consumers |");
            builder.AppendLine("| --- | --- | --- | --- | --- |");
            foreach (var pass in report.Gates.Passes)
            {
                var consumers = string.Join(", ", pass.Consumers.Select(c => $"`{c}`"));
                builder.AppendLine($"| `{pass.Object}` | `{pass.Gate}` | {Date(pass.ExpandedAt)} | {Date(pass.ColdAt)} | {consumers} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Clean history: every removal has a measured window and a gate pass, every backfill is batched, and every drop is isolated and late.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Evidence |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var evidence = finding.Evidence.Count == 0
                    ? "—"
                    : string.Join(" · ", finding.Evidence.Select(e => $"`{e}`"));
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {evidence} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Migrations.Count} migration(s), {report.StatementCount} statement(s) — " +
                           $"{report.Count(MigrationKind.Expand)} expand, {report.Count(MigrationKind.Migrate)} migrate, " +
                           $"{report.Count(MigrationKind.Contract)} contract; {report.Findings.Count} finding(s) — " +
                           $"{report.Errors} error(s), {report.Warnings} warning(s). " +
                           "Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(MigrationLintConfig config, MigrationLintReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"migrationsDir\": {J(config.MigrationsDir)},");
        builder.AppendLine("  \"migrations\": [");
        for (var i = 0; i < report.Migrations.Count; i++)
        {
            var migration = report.Migrations[i];
            var comma = i < report.Migrations.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"file\": {J(migration.FileName)}, \"date\": {J(migration.Date.ToString("yyyy-MM-dd"))}, " +
                               $"\"expand\": {migration.Count(MigrationKind.Expand)}, \"migrate\": {migration.Count(MigrationKind.Migrate)}, " +
                               $"\"contract\": {migration.Count(MigrationKind.Contract)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"gates\": [");
        if (report.Gates is not null)
        {
            for (var i = 0; i < report.Gates.Passes.Count; i++)
            {
                var pass = report.Gates.Passes[i];
                var comma = i < report.Gates.Passes.Count - 1 ? "," : string.Empty;
                var consumers = string.Join(", ", pass.Consumers.Select(J));
                builder.AppendLine($"    {{ \"object\": {J(pass.Object)}, \"gate\": {J(pass.Gate)}, " +
                                   $"\"expandedAt\": {DateJ(pass.ExpandedAt)}, \"coldAt\": {DateJ(pass.ColdAt)}, " +
                                   $"\"consumers\": [{consumers}] }}{comma}");
            }
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.RenderedFindings.Count; i++)
        {
            var finding = report.RenderedFindings[i];
            var comma = i < report.RenderedFindings.Count - 1 ? "," : string.Empty;
            var evidence = string.Join(", ", finding.Evidence.Select(J));
            builder.AppendLine($"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, " +
                               $"\"message\": {J(finding.Message)}, \"evidence\": [{evidence}] }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Date(DateOnly? date) => date?.ToString("yyyy-MM-dd") ?? "—";

    private static string DateJ(DateOnly? date) => date is null ? "null" : J(date.Value.ToString("yyyy-MM-dd"));

    private static string J(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }
}
