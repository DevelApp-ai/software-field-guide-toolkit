using System.Text;

namespace Sfg.Toolkit.BiasProbe;

/// <summary>
/// Renders the bias probe board (#78): bias-probe.md (the human board),
/// bias-probe.json (the machine summary), and the committed baseline written
/// by --update-baseline. All deterministic: sorted, no timestamps,
/// byte-identical on regeneration.
/// </summary>
public static class BiasProbeRenderer
{
    public const string Generator = "sfg bias-probe 0.10.0";

    public static string Markdown(BiasProbeConfig config, BiasReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Bias probe board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — suite **{config.Name}**, run **{report.RunName}**, judge `{config.Judge}`.");
        builder.AppendLine();
        builder.AppendLine("Consistency is measured, not vibes: a counterfactual pair is consistent only when both legs record the same dimension score.");
        builder.AppendLine();

        builder.AppendLine("## Counterfactual consistency");
        builder.AppendLine();
        builder.AppendLine("| Pair | Dimension | A | B | Verdict |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var row in report.PairRows)
        {
            var verdict = row.Consistent is null ? "unmeasured" :
                row.Consistent.Value ? "consistent" : "inconsistent";
            builder.AppendLine($"| `{row.PairId}` | `{row.Dimension}` | " +
                               $"{(row.ScoreA is null ? "—" : Num(row.ScoreA.Value))} | " +
                               $"{(row.ScoreB is null ? "—" : Num(row.ScoreB.Value))} | {verdict} |");
        }

        builder.AppendLine();
        builder.AppendLine($"Rate {Num(report.Consistency)} across {report.PairConsistency.Count} measured pair(s) " +
                           $"— floor {Num(config.ConsistencyFloor)}.");

        builder.AppendLine();
        builder.AppendLine("## Cohort-sliced metrics");
        builder.AppendLine();
        builder.AppendLine("| Metric | Cohort | Observed | Threshold | Verdict |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var metric in report.Metrics)
        {
            var threshold = config.ThresholdOf(metric.Metric);
            builder.AppendLine($"| `{metric.Metric}` | overall | {Num(metric.Overall)} | {Num(threshold)} | " +
                               $"{Verdict(metric.Overall, threshold, metric.Metric, report, cohort: null)} |");
            foreach (var cohort in metric.Cohorts)
            {
                builder.AppendLine($"| `{metric.Metric}` | `{cohort.Cohort}` | {Num(cohort.Value)} | {Num(threshold)} | " +
                                   $"{Verdict(cohort.Value, threshold, metric.Metric, report, cohort.Cohort)} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Refusal asymmetry");
        builder.AppendLine();
        if (report.Refusal.Count == 0)
        {
            builder.AppendLine("No should-succeed case in this run — refusal symmetry is not measurable.");
        }
        else
        {
            builder.AppendLine("| Cohort | Should-succeed | Refused | Rate |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var row in report.Refusal)
            {
                builder.AppendLine($"| `{row.Cohort}` | {row.ShouldSucceed} | {row.Refused} | {Num(row.Rate)} |");
            }

            builder.AppendLine();
            builder.AppendLine($"Delta {Num(report.RefusalDelta)} across {report.Refusal.Count} cohort(s) " +
                               $"— ceiling {Num(config.RefusalDeltaMax)}.");
        }

        builder.AppendLine();
        builder.AppendLine("## Citation balance");
        builder.AppendLine();
        if (report.TotalCitations == 0)
        {
            builder.AppendLine("No citations in this run — citation balance is not measurable.");
        }
        else
        {
            builder.AppendLine("| Cohort | Citations | Share | Expected |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var row in report.Citations)
            {
                builder.AppendLine($"| `{row.Cohort}` | {row.Count} | {Num(row.Share)} | {Num(row.Expected)} |");
            }

            builder.AppendLine();
            builder.AppendLine($"Share is against {report.TotalCitations} citation(s), band ±{Num(config.CitationDeltaMax)}.");
        }

        builder.AppendLine();
        builder.AppendLine("## Judge calibration (against the human-labeled sample)");
        builder.AppendLine();
        builder.AppendLine($"Sample size {report.LabeledSampleSize}, judge `{config.Judge}` agrees on {report.JudgeAgrees} " +
                           $"(agreement {report.Agreement:0.####}), disagrees on {report.JudgeDisagrees}, abstains on {report.JudgeAbstains} — abstentions never count as agreement.");
        if (report.JudgeDisagreementCases.Count > 0)
        {
            builder.AppendLine();
            builder.AppendLine($"Disagreements: {string.Join(", ", report.JudgeDisagreementCases.Select(id => $"`{id}`"))} — calibrate the judge or relabel the cases before its verdicts gate anything.");
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Clean run: every counterfactual pair is consistent, every cohort sits at or above its threshold and baseline, refusals are symmetric, citations match the declared corpus shares, and the judge is calibrated against a human-labeled sample.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Evidence |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var evidence = finding.Evidence.Count == 0
                    ? "—"
                    : string.Join(" · ", finding.Evidence.Select(e => $"`{e}`"));
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {evidence} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Pairs.Count} pair(s), {report.Cases.Count} case(s), {report.Results.Count} result(s), " +
                           $"{report.Findings.Count} finding(s) — {report.Errors} error(s), {report.Warnings} warning(s). " +
                           "Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(BiasProbeConfig config, BiasReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"suite\": {J(config.Name)},");
        builder.AppendLine($"  \"run\": {J(report.RunName)},");
        builder.AppendLine($"  \"judge\": {J(config.Judge)},");
        builder.AppendLine("  \"consistency\": {");
        builder.AppendLine($"    \"value\": {Num(report.Consistency)}, \"measuredPairs\": {report.PairConsistency.Count}, " +
                            $"\"floor\": {Num(config.ConsistencyFloor)}");
        builder.AppendLine("  },");
        builder.AppendLine("  \"metrics\": {");
        for (var i = 0; i < report.Metrics.Count; i++)
        {
            var metric = report.Metrics[i];
            var comma = i < report.Metrics.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {J(metric.Metric)}: {{ \"overall\": {Num(metric.Overall)}, " +
                               $"\"threshold\": {Num(config.ThresholdOf(metric.Metric))}, \"cases\": {metric.Cases}, \"cohorts\": {{");
            for (var j = 0; j < metric.Cohorts.Count; j++)
            {
                var cohort = metric.Cohorts[j];
                var cohortComma = j < metric.Cohorts.Count - 1 ? "," : string.Empty;
                builder.AppendLine($"      {J(cohort.Cohort)}: {{ \"value\": {Num(cohort.Value)}, \"cases\": {cohort.Cases} }}{cohortComma}");
            }

            builder.AppendLine($"    }} }}{comma}");
        }

        builder.AppendLine("  },");
        builder.AppendLine("  \"refusal\": {");
        for (var i = 0; i < report.Refusal.Count; i++)
        {
            var row = report.Refusal[i];
            var comma = i < report.Refusal.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {J(row.Cohort)}: {{ \"shouldSucceed\": {row.ShouldSucceed}, \"refused\": {row.Refused}, \"rate\": {Num(row.Rate)} }}{comma}");
        }

        builder.AppendLine($"  }},");
        builder.AppendLine($"  \"refusalDelta\": {Num(report.RefusalDelta)}, \"refusalCeiling\": {Num(config.RefusalDeltaMax)},");
        builder.AppendLine("  \"citations\": {");
        for (var i = 0; i < report.Citations.Count; i++)
        {
            var row = report.Citations[i];
            var comma = i < report.Citations.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {J(row.Cohort)}: {{ \"count\": {row.Count}, \"share\": {Num(row.Share)}, \"expected\": {Num(row.Expected)} }}{comma}");
        }

        builder.AppendLine($"  }},");
        builder.AppendLine($"  \"totalCitations\": {report.TotalCitations},");
        builder.AppendLine($"  \"agreement\": {{ \"sample\": {report.LabeledSampleSize}, \"agrees\": {report.JudgeAgrees}, " +
                            $"\"value\": {Num(report.Agreement)}, \"abstains\": {report.JudgeAbstains} }},");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.RenderedFindings.Count; i++)
        {
            var finding = report.RenderedFindings[i];
            var comma = i < report.RenderedFindings.Count - 1 ? "," : string.Empty;
            var evidence = string.Join(", ", finding.Evidence.Select(J));
            builder.AppendLine($"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, " +
                               $"\"message\": {J(finding.Message)}, \"evidence\": [{evidence}] }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>The baseline written by --update-baseline: the counterfactual
    /// consistency rate with per-pair outcomes, plus per-metric aggregates and
    /// cohort slices with per-case scores — so a future regression can cite
    /// exactly the pairs and cases that moved. Deterministic, ordinal-sorted,
    /// no timestamps.</summary>
    public static string BaselineJson(BiasProbeConfig config, BiasReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"suite\": {J(config.Name)},");
        builder.AppendLine("  \"consistency\": {");
        builder.AppendLine($"    \"value\": {Num(report.Consistency)},");
        builder.AppendLine("    \"pairs\": {");
        var pairs = report.PairConsistency.Keys.OrderBy(id => id, StringComparer.Ordinal).ToArray();
        for (var i = 0; i < pairs.Length; i++)
        {
            var comma = i < pairs.Length - 1 ? "," : string.Empty;
            builder.AppendLine($"      {J(pairs[i])}: {report.PairConsistency[pairs[i]]}{comma}");
        }

        builder.AppendLine("    }");
        builder.AppendLine("  },");
        builder.AppendLine("  \"metrics\": {");
        var metricNames = report.Metrics.Select(m => m.Metric).OrderBy(m => m, StringComparer.Ordinal).ToArray();
        for (var i = 0; i < metricNames.Length; i++)
        {
            var metric = report.Metrics.Single(m => m.Metric == metricNames[i]);
            var comma = i < metricNames.Length - 1 ? "," : string.Empty;
            builder.AppendLine($"    {J(metric.Metric)}: {{ \"value\": {Num(metric.Overall)}, \"cases\": {{");
            AppendCaseScores(builder, metric.Metric, null, config, report);
            builder.AppendLine("    }, \"cohorts\": {");
            for (var j = 0; j < metric.Cohorts.Count; j++)
            {
                var cohort = metric.Cohorts[j];
                var cohortComma = j < metric.Cohorts.Count - 1 ? "," : string.Empty;
                builder.AppendLine($"      {J(cohort.Cohort)}: {{ \"value\": {Num(cohort.Value)}, \"cases\": {{");
                AppendCaseScores(builder, metric.Metric, cohort.Cohort, config, report);
                builder.AppendLine($"      }} }}{cohortComma}");
            }

            builder.AppendLine($"    }} }}{comma}");
        }

        builder.AppendLine("  }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>The per-case scores of a metric (or one cohort slice of it),
    /// ordinal-sorted — the population is declared by cases, never guessed.</summary>
    private static void AppendCaseScores(StringBuilder builder, string metric, string? cohort, BiasProbeConfig config, BiasReport report)
    {
        var population = report.Cases
            .Where(c => c.Metrics.Contains(metric, StringComparer.Ordinal) &&
                        (cohort is null || string.Equals(c.Cohort, cohort, StringComparison.Ordinal)))
            .OrderBy(c => c.Id, StringComparer.Ordinal)
            .ToArray();
        var scored = new List<(string CaseId, double Score)>();
        foreach (var probeCase in population)
        {
            var result = report.Results.FirstOrDefault(r => r.Id == probeCase.Id);
            if (result?.Scores.TryGetValue(metric, out var score) == true)
            {
                scored.Add((probeCase.Id, score));
            }
        }

        for (var i = 0; i < scored.Count; i++)
        {
            var comma = i < scored.Count - 1 ? "," : string.Empty;
            var indent = cohort is null ? "      " : "        ";
            builder.AppendLine($"{indent}{J(scored[i].CaseId)}: {Num(scored[i].Score)}{comma}");
        }
    }

    private static string Verdict(double observed, double threshold, string metric, BiasReport report, string? cohort)
    {
        var regressionPrefix = cohort is null ? $"{metric} regressed" : $"{metric} regressed for cohort '{cohort}'";
        if (report.Findings.Any(f => (f.Rule == "bias/baseline-regression" || f.Rule == "bias/cohort-baseline-regression") &&
                                      f.Message.StartsWith(regressionPrefix, StringComparison.Ordinal)))
        {
            return "regressed";
        }

        var improvedPrefix = cohort is null ? $"{metric} improved" : $"{metric} improved for cohort '{cohort}'";
        if (report.Findings.Any(f => (f.Rule == "bias/baseline-improved" || f.Rule == "bias/cohort-baseline-improved") &&
                                      f.Message.StartsWith(improvedPrefix, StringComparison.Ordinal)))
        {
            return "improved";
        }

        return observed < threshold ? "below threshold" : "steady";
    }

    internal static string Num(double value) =>
        value == Math.Floor(value) ? value.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture) + "" :
        value.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture);

    internal static string J(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }
}
