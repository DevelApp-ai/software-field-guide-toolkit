using System.Text;

namespace Sfg.Toolkit.EventHarness;

/// <summary>
/// Renders the event conformance board (#60): events.md (the human board)
/// and events.json (the machine summary). All deterministic: sorted, no
/// timestamps, byte-identical on regeneration.
/// </summary>
public static class EventHarnessRenderer
{
    public const string Generator = "sfg events 0.5.0";

    public static string Markdown(EventHarnessConfig config, ConventionScan scan, EventHarnessSuite suite)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Event contract conformance board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — replay-based chaos-lite against the real consumer, with file:line evidence.");
        builder.AppendLine();
        builder.AppendLine("## Events");
        builder.AppendLine();
        builder.AppendLine("| Event | Version | Cases | Old-schema replay | Probes |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var p in suite.Events)
        {
            var skew = p.Contract.PreviousVersion is null
                ? "—"
                : $"v{p.Contract.PreviousVersion}, {p.SkewCaseCount} skew cases (`{p.Contract.SkewCases}`)";
            var probes = 3 + (p.Contract.PreviousVersion is null ? 0 : 1);
            builder.AppendLine(
                $"| `{p.Contract.Id}` | {p.Contract.Version} | {p.CaseCount} (`{p.Contract.Cases}`) | {skew} | {probes} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Scenarios replayed per event");
        builder.AppendLine();
        builder.AppendLine("- duplicate delivery — the message id is applied exactly once");
        builder.AppendLine("- out-of-order arrival — every case still applies");
        builder.AppendLine("- poison payloads — routed to the dead letters, never a crash");
        builder.AppendLine("- old-schema replay — applied or dead-lettered, never lost (only events that declare a previous version)");
        builder.AppendLine();
        builder.AppendLine("## Conventions verified");
        builder.AppendLine();
        builder.AppendLine($"Consumer `{scan.Consumer.Name}` (`{scan.Consumer.File}:{scan.Consumer.Line}`):");
        foreach (var member in scan.ConsumerMembers)
        {
            builder.AppendLine($"- `{member.Name}` ({member.Kind}, `{member.File}:{member.Line}`)");
        }

        builder.AppendLine();
        if (scan.Outbox is not null)
        {
            builder.AppendLine($"Outbox `{scan.Outbox.Name}` (`{scan.Outbox.File}:{scan.Outbox.Line}`):");
            foreach (var member in scan.OutboxMembers)
            {
                builder.AppendLine($"- `{member.Name}` ({member.Kind}, `{member.File}:{member.Line}`)");
            }
        }
        else
        {
            builder.AppendLine("No outbox declared in the contract — producer-side health probes are skipped.");
        }

        builder.AppendLine();
        var consumerProbes = suite.Events.Sum(p => 3 + (p.Contract.PreviousVersion is null ? 0 : 1));
        var outboxProbes = scan.Outbox is null ? 0 : 2;
        builder.AppendLine($"Summary: {suite.Events.Count} events, {consumerProbes} consumer probes, {outboxProbes} outbox probes, " +
                          $"{suite.Files.Count} suite files (run with: dotnet test EventConformance.csproj).");
        return builder.ToString();
    }

    public static string Json(EventHarnessConfig config, ConventionScan scan, EventHarnessSuite suite)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {Json(Generator)},");
        builder.AppendLine($"  \"consumer\": {{ \"name\": {Json(scan.Consumer.Name)}, \"file\": {Json(scan.Consumer.File)}, \"line\": {scan.Consumer.Line} }},");
        if (scan.Outbox is not null)
        {
            builder.AppendLine($"  \"outbox\": {{ \"name\": {Json(scan.Outbox.Name)}, \"file\": {Json(scan.Outbox.File)}, \"line\": {scan.Outbox.Line} }},");
        }
        else
        {
            builder.AppendLine("  \"outbox\": null,");
        }

        builder.AppendLine($"  \"targetProject\": {Json(System.IO.Path.GetFileName(scan.TargetProject))},");
        builder.AppendLine($"  \"targetFramework\": {Json(scan.TargetFramework)},");
        builder.AppendLine("  \"events\": [");
        for (var i = 0; i < suite.Events.Count; i++)
        {
            var p = suite.Events[i];
            var comma = i < suite.Events.Count - 1 ? "," : string.Empty;
            var skew = p.Contract.PreviousVersion is null
                ? "\"previousVersion\": null, \"skewCaseCount\": 0"
                : $"\"previousVersion\": {p.Contract.PreviousVersion}, \"skewCaseCount\": {p.SkewCaseCount}";
            builder.AppendLine(
                $"    {{ \"id\": {Json(p.Contract.Id)}, \"version\": {p.Contract.Version}, \"cases\": {Json(p.Contract.Cases)}, " +
                $"\"caseCount\": {p.CaseCount}, {skew} }}{comma}");
        }

        builder.AppendLine("  ]");
        builder.Append("}");
        return builder.ToString();
    }

    private static string Json(string value) => "\"" + System.Text.Json.JsonEncodedText.Encode(value) + "\"";
}
