using System.Text;
using System.Text.Json;

namespace Sfg.Toolkit.EventHarness;

public sealed record EventGeneratedFile(string Path, string Content);

public sealed record PreparedEvent(
    EventContract Contract,
    string CasesJson,
    int CaseCount,
    string? SkewCasesJson,
    int SkewCaseCount);

public sealed record EventHarnessSuite(
    IReadOnlyList<EventGeneratedFile> Files,
    IReadOnlyList<PreparedEvent> Events,
    bool HasOutbox);

/// <summary>
/// Generates the event contract conformance suite (#60): a compilable xunit
/// project that replays seeded chaos-lite against the real consumer —
/// duplicate deliveries, out-of-order arrivals, poison payloads (routed to
/// the dead letters, never a crash), and old-schema producer replays — plus
/// producer-side outbox health probes. Convention and case declarations are
/// recorded with file:line evidence in the manifest. Deterministic:
/// byte-identical on regeneration, safe to diff and commit.
/// </summary>
public static class EventHarnessGenerator
{
    private const string Header = "// Generated by sfg events — do not edit; regenerate instead.";
    private const string TestSdkVersion = "17.11.1";
    private const string XunitVersion = "2.9.2";
    private const string XunitRunnerVersion = "2.8.2";
    private const string BaseIndent = "        ";

    public static EventHarnessSuite Generate(
        string root,
        string outDir,
        EventHarnessConfig config,
        ConventionScan scan)
    {
        root = Path.GetFullPath(root);
        outDir = Path.GetFullPath(outDir);

        var prepared = new List<PreparedEvent>();
        foreach (var contract in config.Events)
        {
            prepared.Add(Prepare(root, contract));
        }

        var projectReference = Path.GetRelativePath(outDir, Path.GetFullPath(scan.TargetProject)).Replace('\\', '/');

        var files = new List<EventGeneratedFile>
        {
            new("EventConformance.csproj", Csproj(projectReference, scan.TargetFramework)),
            new("EventConformanceHarness.cs", Harness()),
            new("ConsumerProbes.cs", ConsumerProbes(prepared, scan)),
            new("Cases.cs", Cases(prepared)),
            new("manifest.json", Manifest(config, scan, projectReference, prepared)),
            new("README.md", Readme(prepared, scan, projectReference)),
        };
        if (scan.Outbox is not null)
        {
            files.Insert(3, new EventGeneratedFile("OutboxProbes.cs", OutboxProbes(scan)));
        }

        return new EventHarnessSuite(files, prepared, scan.Outbox is not null);
    }

    private static PreparedEvent Prepare(string root, EventContract contract)
    {
        var (casesJson, caseCount) = LoadCases(root, contract, contract.Cases, requireArray: true);
        string? skewCasesJson = null;
        var skewCaseCount = 0;
        if (contract.PreviousVersion is not null)
        {
            (skewCasesJson, skewCaseCount) = LoadCases(root, contract, contract.SkewCases!, requireArray: true);
        }

        return new PreparedEvent(contract, casesJson, caseCount, skewCasesJson, skewCaseCount);
    }

    private static (string Json, int Count) LoadCases(string root, EventContract contract, string cases, bool requireArray)
    {
        var casesPath = Path.Combine(root, cases);
        if (!File.Exists(casesPath))
        {
            throw new InvalidOperationException(
                $"event '{contract.Id}': cases file not found: {cases} — events need \"cases\" payloads to replay");
        }

        var casesJson = File.ReadAllText(casesPath);
        if (casesJson.Contains("\"\"\"", StringComparison.Ordinal))
        {
            throw new InvalidOperationException(
                $"event '{contract.Id}': cases file {cases} contains a raw string delimiter (\"\"\") — " +
                "case payloads cannot be embedded verbatim");
        }

        int count;
        try
        {
            using var document = JsonDocument.Parse(casesJson);
            if (document.RootElement.ValueKind != JsonValueKind.Array)
            {
                throw new InvalidOperationException(
                    $"event '{contract.Id}': cases file {cases} must be a JSON array of payloads");
            }

            count = document.RootElement.GetArrayLength();
        }
        catch (JsonException exception)
        {
            throw new InvalidOperationException(
                $"event '{contract.Id}': cases file {cases} is not valid JSON: {exception.Message}");
        }

        if (count == 0)
        {
            throw new InvalidOperationException(
                $"event '{contract.Id}': cases file {cases} declares no cases — a replay scenario needs at least one");
        }

        return (casesJson, count);
    }

    private static string Csproj(string projectReference, string targetFramework)
    {
        return $$"""
            <!-- Generated by sfg events — do not edit; regenerate instead. -->
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>{{targetFramework}}</TargetFramework>
                <Nullable>enable</Nullable>
                <ImplicitUsings>enable</ImplicitUsings>
                <IsPackable>false</IsPackable>
              </PropertyGroup>
              <ItemGroup>
                <PackageReference Include="Microsoft.NET.Test.Sdk" Version="{{TestSdkVersion}}" />
                <PackageReference Include="xunit" Version="{{XunitVersion}}" />
                <PackageReference Include="xunit.runner.visualstudio" Version="{{XunitRunnerVersion}}" />
              </ItemGroup>
              <ItemGroup>
                <ProjectReference Include="{{projectReference}}" />
              </ItemGroup>
            </Project>
            """;
    }

    private static string Harness()
    {
        return """
            // Generated by sfg events — do not edit; regenerate instead.
            #nullable enable
            namespace EventConformance;

            /// <summary>
            /// Event conformance harness (#60): envelope builder, case loader, and
            /// poison corpus for the replay probes. The probes deliver real
            /// envelopes — duplicates, out-of-order arrivals, poison payloads, and
            /// old-schema producer replays — to the real consumer; a compliant
            /// consumer passes, a naive one fails loudly.
            /// </summary>
            public static class EventConformanceHarness
            {
                /// <summary>
                /// Builds a delivery envelope around one payload:
                /// {"id":"...","type":"...","version":N,"payload":{...}}.
                /// </summary>
                public static string Envelope(string id, string type, int version, string payloadJson)
                {
                    var idJson = System.Text.Json.JsonEncodedText.Encode(id);
                    var typeJson = System.Text.Json.JsonEncodedText.Encode(type);
                    return $"{{\"id\":\"{idJson}\",\"type\":\"{typeJson}\",\"version\":{version},\"payload\":{payloadJson}}}";
                }

                /// <summary>The raw payloads of a cases file, as JSON texts.</summary>
                public static string[] Payloads(string casesJson)
                {
                    using var document = System.Text.Json.JsonDocument.Parse(casesJson);
                    if (document.RootElement.ValueKind != System.Text.Json.JsonValueKind.Array)
                    {
                        throw new System.InvalidOperationException("cases must be a JSON array of payloads");
                    }

                    var payloads = new List<string>();
                    foreach (var element in document.RootElement.EnumerateArray())
                    {
                        payloads.Add(element.GetRawText());
                    }

                    return payloads.ToArray();
                }

                /// <summary>
                /// The poison corpus for one event: malformed JSON, a non-object
                /// message, and a type-violating envelope (the payload is not an
                /// object). A consumer must route every one to the dead letters —
                /// never crash.
                /// </summary>
                public static string[] PoisonCorpus(string type, int version)
                {
                    return new[]
                    {
                        "{",
                        "[]",
                        Envelope("poison-1", type, version, "\"payload-is-not-an-object\""),
                    };
                }
            }
            """;
    }

    private static string ConsumerProbes(IReadOnlyList<PreparedEvent> prepared, ConventionScan scan)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using Xunit;");
        if (!string.IsNullOrWhiteSpace(scan.Consumer.Namespace))
        {
            builder.AppendLine($"using {scan.Consumer.Namespace};");
        }

        builder.AppendLine();
        builder.AppendLine("namespace EventConformance;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Consumer conformance probes (#60): seeded chaos-lite replayed against");
        builder.AppendLine("/// the real consumer. Duplicate deliveries must apply exactly once,");
        builder.AppendLine("/// out-of-order arrivals must all apply, poison payloads must route to the");
        builder.AppendLine("/// dead letters without crashing, and old-schema producer replays must");
        builder.AppendLine("/// never lose a message. A naive consumer fails these loudly.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public sealed class ConsumerProbes");
        builder.AppendLine("{");
        for (var i = 0; i < prepared.Count; i++)
        {
            var p = prepared[i];
            var name = Pascal(p.Contract.Id);
            var type = p.Contract.Id;
            var version = p.Contract.Version;
            if (i > 0)
            {
                builder.AppendLine();
            }

            builder.AppendLine("    [Fact]");
            builder.AppendLine($"    public void {name}_duplicate_delivery_applies_exactly_once()");
            builder.AppendLine("    {");
            builder.AppendLine($"        var consumer = new {scan.Consumer.Name}();");
            builder.AppendLine($"        var payloads = EventConformanceHarness.Payloads(Cases.{name});");
            builder.AppendLine("        for (var index = 0; index < payloads.Length; index++)");
            builder.AppendLine("        {");
            builder.AppendLine("            var id = $\"case-{index}\";");
            builder.AppendLine($"            var envelope = EventConformanceHarness.Envelope(id, \"{type}\", {version}, payloads[index]);");
            builder.AppendLine("            consumer.Handle(envelope);");
            builder.AppendLine("            consumer.Handle(envelope);");
            builder.AppendLine();
            builder.AppendLine("            var applied = consumer.AppliedEffects.Count(effect => effect == id);");
            builder.AppendLine("            Assert.True(applied == 1,");
            builder.AppendLine($"                $\"EVENT CONTRACT violated on '{type}': duplicate delivery applied '{{id}}' {{applied}} times — \" +");
            builder.AppendLine("                \"at-least-once delivery demands exactly-once effects\");");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine();
            builder.AppendLine("    [Fact]");
            builder.AppendLine($"    public void {name}_out_of_order_arrival_still_applies()");
            builder.AppendLine("    {");
            builder.AppendLine($"        var consumer = new {scan.Consumer.Name}();");
            builder.AppendLine($"        var payloads = EventConformanceHarness.Payloads(Cases.{name});");
            builder.AppendLine("        for (var index = payloads.Length - 1; index >= 0; index--)");
            builder.AppendLine("        {");
            builder.AppendLine($"            consumer.Handle(EventConformanceHarness.Envelope($\"case-{{index}}\", \"{type}\", {version}, payloads[index]));");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        for (var index = 0; index < payloads.Length; index++)");
            builder.AppendLine("        {");
            builder.AppendLine("            Assert.Contains($\"case-{index}\", consumer.AppliedEffects);");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine();
            builder.AppendLine("    [Fact]");
            builder.AppendLine($"    public void {name}_poison_routes_to_the_dead_letters_never_crashes()");
            builder.AppendLine("    {");
            builder.AppendLine($"        var consumer = new {scan.Consumer.Name}();");
            builder.AppendLine($"        var corpus = EventConformanceHarness.PoisonCorpus(\"{type}\", {version});");
            builder.AppendLine("        foreach (var poison in corpus)");
            builder.AppendLine("        {");
            builder.AppendLine("            try");
            builder.AppendLine("            {");
            builder.AppendLine("                consumer.Handle(poison);");
            builder.AppendLine("            }");
            builder.AppendLine("            catch (System.Exception exception)");
            builder.AppendLine("            {");
            builder.AppendLine("                Assert.Fail(");
            builder.AppendLine($"                    $\"EVENT CONTRACT violated on '{type}': a poison payload crashed the consumer \" +");
            builder.AppendLine("                    ($\"({exception.GetType().Name}: {exception.Message}) — poison must route to the dead-letter queue, never crash\"));");
            builder.AppendLine("            }");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        foreach (var poison in corpus)");
            builder.AppendLine("        {");
            builder.AppendLine("            Assert.Contains(poison, consumer.DeadLetters);");
            builder.AppendLine("        }");
            builder.AppendLine("    }");

            if (p.Contract.PreviousVersion is not null)
            {
                builder.AppendLine();
                builder.AppendLine("    [Fact]");
                builder.AppendLine($"    public void {name}_old_schema_replay_is_never_lost()");
                builder.AppendLine("    {");
                builder.AppendLine($"        var consumer = new {scan.Consumer.Name}();");
                builder.AppendLine($"        var payloads = EventConformanceHarness.Payloads(Cases.{name}Skew);");
                builder.AppendLine("        for (var index = 0; index < payloads.Length; index++)");
                builder.AppendLine("        {");
                builder.AppendLine("            var id = $\"skew-{index}\";");
                builder.AppendLine($"            var envelope = EventConformanceHarness.Envelope(id, \"{type}\", {p.Contract.PreviousVersion}, payloads[index]);");
                builder.AppendLine("            consumer.Handle(envelope);");
                builder.AppendLine();
                builder.AppendLine("            var applied = consumer.AppliedEffects.Contains(id);");
                builder.AppendLine("            var deadLettered = consumer.DeadLetters.Contains(envelope);");
                builder.AppendLine("            Assert.True(applied || deadLettered,");
                builder.AppendLine($"                $\"EVENT CONTRACT violated on '{type}': old-schema replay '{{id}}' (v{p.Contract.PreviousVersion}) was \" +");
                builder.AppendLine("                \"neither applied nor dead-lettered — version skew must never lose a message\");");
                builder.AppendLine("        }");
                builder.AppendLine("    }");
            }
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string OutboxProbes(ConventionScan scan)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using Xunit;");
        if (!string.IsNullOrWhiteSpace(scan.Outbox!.Namespace))
        {
            builder.AppendLine($"using {scan.Outbox.Namespace};");
        }

        builder.AppendLine();
        builder.AppendLine("namespace EventConformance;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Outbox health probes (#60): the producer side of the contract. A");
        builder.AppendLine("/// publish must wait in the pending queue, and a double dispatch must");
        builder.AppendLine("/// stay idempotent — the outbox never drops a send and never double-sends.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public sealed class OutboxProbes");
        builder.AppendLine("{");
        builder.AppendLine("    [Fact]");
        builder.AppendLine("    public void Published_messages_wait_in_the_pending_queue()");
        builder.AppendLine("    {");
        builder.AppendLine($"        var outbox = new {scan.Outbox.Name}();");
        builder.AppendLine("        outbox.Publish(\"ob-0\");");
        builder.AppendLine("        Assert.Contains(\"ob-0\", outbox.Pending);");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    [Fact]");
        builder.AppendLine("    public void Double_dispatch_is_idempotent()");
        builder.AppendLine("    {");
        builder.AppendLine($"        var outbox = new {scan.Outbox.Name}();");
        builder.AppendLine("        outbox.Publish(\"ob-1\");");
        builder.AppendLine("        outbox.MarkDispatched(\"ob-1\");");
        builder.AppendLine("        outbox.MarkDispatched(\"ob-1\");");
        builder.AppendLine("        Assert.Equal(1, outbox.Dispatched.Count(id => id == \"ob-1\"));");
        builder.AppendLine("        Assert.DoesNotContain(\"ob-1\", outbox.Pending);");
        builder.AppendLine("        Assert.Empty(outbox.Pending);");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Cases(IReadOnlyList<PreparedEvent> prepared)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace EventConformance;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Event case payloads, embedded verbatim from the application's case");
        builder.AppendLine("/// files. Regenerate with sfg events; do not edit.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public static class Cases");
        builder.AppendLine("{");
        var first = true;
        foreach (var p in prepared)
        {
            var name = Pascal(p.Contract.Id);
            foreach (var (constName, json) in new[]
                     {
                         (name, p.CasesJson),
                         p.SkewCasesJson is null ? (string.Empty, string.Empty) : (name + "Skew", p.SkewCasesJson),
                     })
            {
                if (constName.Length == 0)
                {
                    continue;
                }

                if (!first)
                {
                    builder.AppendLine();
                }

                first = false;
                builder.AppendLine($"    public const string {constName} = \"\"\"");
                foreach (var rawLine in json.Replace("\r\n", "\n").Split('\n'))
                {
                    builder.AppendLine(rawLine.Length == 0 ? string.Empty : BaseIndent + rawLine);
                }

                builder.AppendLine("        \"\"\";");
            }
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Manifest(
        EventHarnessConfig config,
        ConventionScan scan,
        string projectReference,
        IReadOnlyList<PreparedEvent> prepared)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {Json(EventHarnessRenderer.Generator)},");
        builder.AppendLine($"  \"consumer\": {{ \"name\": {Json(scan.Consumer.Name)}, \"file\": {Json(scan.Consumer.File)}, \"line\": {scan.Consumer.Line}, \"members\": [");
        builder.AppendLine(Members(scan.ConsumerMembers, 4, trailingComma: false));
        builder.AppendLine("  ] },");
        if (scan.Outbox is not null)
        {
            builder.AppendLine($"  \"outbox\": {{ \"name\": {Json(scan.Outbox.Name)}, \"file\": {Json(scan.Outbox.File)}, \"line\": {scan.Outbox.Line}, \"members\": [");
            builder.AppendLine(Members(scan.OutboxMembers, 4, trailingComma: false));
            builder.AppendLine("  ] },");
        }
        else
        {
            builder.AppendLine("  \"outbox\": null,");
        }

        builder.AppendLine($"  \"targetProject\": {Json(Path.GetFileName(scan.TargetProject))},");
        builder.AppendLine($"  \"targetFramework\": {Json(scan.TargetFramework)},");
        builder.AppendLine($"  \"projectReference\": {Json(projectReference)},");
        builder.AppendLine("  \"scenarios\": [");
        builder.AppendLine("    \"duplicate-delivery\",");
        builder.AppendLine("    \"out-of-order-arrival\",");
        builder.AppendLine("    \"poison-payloads\",");
        builder.AppendLine("    \"version-skew\"");
        builder.AppendLine("  ],");
        builder.AppendLine("  \"events\": [");
        for (var i = 0; i < prepared.Count; i++)
        {
            var p = prepared[i];
            var comma = i < prepared.Count - 1 ? "," : string.Empty;
            var skew = p.Contract.PreviousVersion is null
                ? "\"previousVersion\": null, \"skewCases\": \"\", \"skewCaseCount\": 0"
                : $"\"previousVersion\": {p.Contract.PreviousVersion}, \"skewCases\": {Json(p.Contract.SkewCases ?? string.Empty)}, \"skewCaseCount\": {p.SkewCaseCount}";
            builder.AppendLine(
                $"    {{ \"id\": {Json(p.Contract.Id)}, \"version\": {p.Contract.Version}, " +
                $"\"cases\": {Json(p.Contract.Cases)}, \"caseCount\": {p.CaseCount}, {skew} }}{comma}");
        }

        builder.AppendLine("  ]");
        builder.Append("}");
        return builder.ToString();
    }

    private static string Members(IReadOnlyList<ConventionMember> members, int indent, bool trailingComma)
    {
        var pad = new string(' ', indent);
        var builder = new StringBuilder();
        for (var i = 0; i < members.Count; i++)
        {
            var m = members[i];
            var comma = i < members.Count - 1 || trailingComma ? "," : string.Empty;
            builder.Append($"{pad}{{ \"name\": {Json(m.Name)}, \"kind\": {Json(m.Kind)}, \"file\": {Json(m.File)}, \"line\": {m.Line} }}{comma}\n");
        }

        return builder.ToString(0, builder.Length - 1);
    }

    private static string Readme(IReadOnlyList<PreparedEvent> prepared, ConventionScan scan, string projectReference)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Event contract conformance suite");
        builder.AppendLine();
        builder.AppendLine("Generated by `sfg events` against the event contract. This suite runs in CI so a " +
                          "consumer that silently drops duplicates, crashes on poison, or loses old-schema replays cannot pass review.");
        builder.AppendLine();
        builder.AppendLine("## Run");
        builder.AppendLine();
        builder.AppendLine("```bash");
        builder.AppendLine("dotnet test EventConformance.csproj");
        builder.AppendLine("```");
        builder.AppendLine();
        builder.AppendLine("## What each probe bites on");
        builder.AppendLine();
        builder.AppendLine("| Probe | Event | Version | Cases | Old-schema replay |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var p in prepared)
        {
            var name = Pascal(p.Contract.Id);
            var skew = p.Contract.PreviousVersion is null
                ? "—"
                : $"v{p.Contract.PreviousVersion}, {p.SkewCaseCount} cases (`{p.Contract.SkewCases}`)";
            builder.AppendLine(
                $"| `{name}_duplicate_delivery_applies_exactly_once` | `{p.Contract.Id}` | {p.Contract.Version} | {p.CaseCount} (`{p.Contract.Cases}`) | {skew} |");
            builder.AppendLine(
                $"| `{name}_out_of_order_arrival_still_applies` | `{p.Contract.Id}` | {p.Contract.Version} | {p.CaseCount} (`{p.Contract.Cases}`) | {skew} |");
            builder.AppendLine(
                $"| `{name}_poison_routes_to_the_dead_letters_never_crashes` | `{p.Contract.Id}` | {p.Contract.Version} | fixed corpus | {skew} |");
            if (p.Contract.PreviousVersion is not null)
            {
                builder.AppendLine(
                    $"| `{name}_old_schema_replay_is_never_lost` | `{p.Contract.Id}` | {p.Contract.Version} | {p.SkewCaseCount} (`{p.Contract.SkewCases}`) | {skew} |");
            }
        }

        if (scan.Outbox is not null)
        {
            builder.AppendLine(
                $"| `Published_messages_wait_in_the_pending_queue` | outbox `{scan.Outbox.Name}` (`{scan.Outbox.File}:{scan.Outbox.Line}`) | — | — | — |");
            builder.AppendLine(
                $"| `Double_dispatch_is_idempotent` | outbox `{scan.Outbox.Name}` (`{scan.Outbox.File}:{scan.Outbox.Line}`) | — | — | — |");
        }

        builder.AppendLine();
        builder.AppendLine($"Target: `{projectReference}`. Consumer: `{scan.Consumer.Name}` (`{scan.Consumer.File}:{scan.Consumer.Line}`). " +
                          "A failure prefixed `EVENT CONTRACT violated on '...'` names the event, the message id, and the broken guarantee — " +
                          "fix the consumer or the outbox; never the probe.");
        return builder.ToString();
    }

    private static string Pascal(string id)
    {
        var parts = id.Split(new[] { '.', '-', '_', '/', ' ' }, StringSplitOptions.RemoveEmptyEntries);
        var builder = new StringBuilder();
        foreach (var part in parts)
        {
            builder.Append(char.ToUpperInvariant(part[0]));
            if (part.Length > 1)
            {
                builder.Append(part[1..]);
            }
        }

        return builder.ToString();
    }

    private static string Json(string value) => "\"" + System.Text.Json.JsonEncodedText.Encode(value) + "\"";
}
