using System.Globalization;
using System.Text;

namespace Sfg.Toolkit.ReviewCalib;

/// <summary>
/// Renders the reviewer calibration board (#77): review-calib.md (the human
/// board) and review-calib.json (the machine summary). Deterministic:
/// ordinal order everywhere, no timestamps of the run, byte-identical on
/// regeneration. A calibration instrument, never a leaderboard.
/// </summary>
public static class ReviewCalibRenderer
{
    public const string Generator = "sfg review-calib 0.9.0";

    public static string Markdown(ReviewCalibConfig config, ReviewCalibEventsExport export, ReviewCalibReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Reviewer calibration board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — {report.Reviews.Count} review decision(s) " +
                           $"({report.SeededCount} seeded) from `{export.FileName}`" +
                           (report.Repository is null ? string.Empty : $" ({report.Repository}") +
                           (report.Window is null ? string.Empty : $", window {report.Window}") +
                           (report.Repository is null ? string.Empty : ")") +
                           $", anchored at {report.Today}.");
        builder.AppendLine();
        builder.AppendLine("Calibration instrument, never a leaderboard: the rates below measure queues against " +
                           "seeded defects and a recorded judge — evidence for the autonomy ladder, never a ranking of people.");
        builder.AppendLine();

        builder.AppendLine("## Catch rates by role");
        builder.AppendLine();
        builder.AppendLine("| Role | Reviews | Seeded | Caught | Catch rate |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var role in report.Roles)
        {
            builder.AppendLine($"| {role.Role} | {role.Reviews} | {role.Seeded} | {role.Caught} | {Rate(role.CatchRate)} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Queue telemetry");
        builder.AppendLine();
        builder.AppendLine("| Queue | Reviews | Approve | Edit | Reject | Escalate | Approval rate | Median decision (s) |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- |");
        foreach (var queue in report.Queues)
        {
            builder.AppendLine($"| {queue.Queue} | {queue.Reviews} | {queue.Approves} | {queue.Edits} | {queue.Rejects} | " +
                               $"{queue.Escalations} | {Percent(queue.ApprovalRate)} | {Seconds(queue.MedianSeconds)} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Judge calibration");
        builder.AppendLine();
        if (report.JudgeSample == 0)
        {
            builder.AppendLine("No judged row in this export — human-vs-judge calibration is not exercised.");
        }
        else
        {
            builder.Append($"Human decisions against the recorded judge on {report.JudgeSample} row(s): agree " +
                           $"{report.Reviews.Count(r => r.JudgeAgrees == true)}, disagree {report.Disagreements.Count} — " +
                           $"agreement {Agreement(report.Agreement)}");
            if (report.Disagreements.Count > 0)
            {
                builder.Append($". Disagreements: {string.Join(", ", report.Disagreements.Select(id => $"`{id}`"))}");
            }

            builder.AppendLine(".");
        }

        builder.AppendLine();
        builder.AppendLine("## Rung evidence");
        builder.AppendLine();
        builder.AppendLine("The autonomy ladder is earned by people; this table only exports the evidence a rung claim must cite:");
        builder.AppendLine();
        builder.AppendLine("| Queue | Seeded | Caught | Catch rate | Approval rate | Median decision (s) | Judge agreement | Last seeded decided |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- |");
        foreach (var rung in report.Rungs)
        {
            builder.AppendLine($"| {rung.Queue} | {rung.Seeded} | {rung.Caught} | {Rate(rung.CatchRate)} | " +
                               $"{Percent(rung.ApprovalRate)} | {Seconds(rung.MedianSeconds)} | {Agreement(rung.JudgeAgreement)} | " +
                               $"{(rung.LastSeededDecidedAt is null ? "—" : rung.LastSeededDecidedAt.Value.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Clean export: every seeded defect was caught, no queue rubber-stamps its approvals, and every role sits at or above the calibration floor.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Evidence |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var evidence = finding.Evidence.Count == 0
                    ? "—"
                    : string.Join(" · ", finding.Evidence.Select(e => $"`{e}`"));
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {evidence} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Reviews.Count} review(s) ({report.SeededCount} seeded, {report.CaughtCount} caught), " +
                           $"{report.Roles.Count} role(s), {report.Queues.Count} queue(s) — " +
                           (report.JudgeSample == 0
                               ? "no judged row"
                               : $"judge agreement {Agreement(report.Agreement)} on {report.JudgeSample} judged row(s)") +
                           $" — {report.Findings.Count} finding(s) — {report.Errors} error(s), {report.Warnings} warning(s). " +
                           "Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(ReviewCalibConfig config, ReviewCalibEventsExport export, ReviewCalibReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"events\": {J(export.FileName)},");
        builder.AppendLine($"  \"today\": {J(report.Today)},");
        if (report.Repository is not null)
        {
            builder.AppendLine($"  \"repository\": {J(report.Repository)},");
        }

        if (report.Window is not null)
        {
            builder.AppendLine($"  \"window\": {J(report.Window)},");
        }

        builder.AppendLine($"  \"counts\": {{ \"reviews\": {report.Reviews.Count}, \"seeded\": {report.SeededCount}, \"caught\": {report.CaughtCount} }},");
        builder.AppendLine("  \"roles\": [");
        for (var i = 0; i < report.Roles.Count; i++)
        {
            var role = report.Roles[i];
            var comma = i < report.Roles.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"role\": {J(role.Role)}, \"reviews\": {role.Reviews}, \"seeded\": {role.Seeded}, " +
                               $"\"caught\": {role.Caught}, \"catchRate\": {RateJ(role.CatchRate)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"queues\": [");
        for (var i = 0; i < report.Queues.Count; i++)
        {
            var queue = report.Queues[i];
            var comma = i < report.Queues.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"queue\": {J(queue.Queue)}, \"reviews\": {queue.Reviews}, \"approves\": {queue.Approves}, " +
                               $"\"edits\": {queue.Edits}, \"rejects\": {queue.Rejects}, \"escalations\": {queue.Escalations}, " +
                               $"\"approvalRate\": {RateJ(queue.ApprovalRate)}, \"medianSeconds\": {Seconds(queue.MedianSeconds)}, " +
                               $"\"seeded\": {queue.Seeded}, \"caught\": {queue.Caught}, \"catchRate\": {RateJ(queue.CatchRate)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"judge\": {{ \"sample\": {report.JudgeSample}, \"agreement\": {AgreementJ(report.Agreement)}, " +
                           $"\"disagreements\": [{string.Join(", ", report.Disagreements.Select(J))}] }},");
        builder.AppendLine("  \"rungs\": [");
        for (var i = 0; i < report.Rungs.Count; i++)
        {
            var rung = report.Rungs[i];
            var comma = i < report.Rungs.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"queue\": {J(rung.Queue)}, \"seeded\": {rung.Seeded}, \"caught\": {rung.Caught}, " +
                               $"\"catchRate\": {RateJ(rung.CatchRate)}, \"approvalRate\": {RateJ(rung.ApprovalRate)}, " +
                               $"\"medianSeconds\": {Seconds(rung.MedianSeconds)}, \"judgeAgreement\": {AgreementJ(rung.JudgeAgreement)}, " +
                               $"\"lastSeededDecidedAt\": {(rung.LastSeededDecidedAt is null ? "null" : J(rung.LastSeededDecidedAt.Value.ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture)))} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.RenderedFindings.Count; i++)
        {
            var finding = report.RenderedFindings[i];
            var comma = i < report.RenderedFindings.Count - 1 ? "," : string.Empty;
            var evidence = string.Join(", ", finding.Evidence.Select(J));
            builder.AppendLine($"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, " +
                               $"\"message\": {J(finding.Message)}, \"evidence\": [{evidence}] }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Rate(double? fraction) =>
        fraction is null
            ? "—"
            : Percent(fraction.Value);

    private static string Percent(double fraction) =>
        Math.Round(fraction * 100.0, 1, MidpointRounding.AwayFromZero)
            .ToString("0.0", CultureInfo.InvariantCulture) + "%";

    private static string RateJ(double? fraction) =>
        fraction is null ? "null" : fraction.Value.ToString("0.####", CultureInfo.InvariantCulture);

    private static string AgreementJ(double? agreement) =>
        agreement is null ? "null" : agreement.Value.ToString("0.####", CultureInfo.InvariantCulture);

    private static string Agreement(double? agreement) =>
        agreement is null ? "—" : agreement.Value.ToString("0.####", CultureInfo.InvariantCulture);

    private static string Seconds(double value) => value.ToString("0.0", CultureInfo.InvariantCulture);

    private static string J(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }
}