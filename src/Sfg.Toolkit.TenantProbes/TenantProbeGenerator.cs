    private static string Manifest(string root, EfModelScan model, TenantProbeConfig config, string projectReference, string targetFramework)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($@"  ""generator"": ""sfg tenant-probes 0.10.0"",");
        builder.AppendLine($@"  ""targetProject"": {Json(Path.GetFileName(model.Context.ProjectPath))},");
        builder.AppendLine($@"  ""targetFramework"": {Json(targetFramework)},");
        builder.AppendLine($@"  ""dbContext"": {Json(model.Context.Name)},");
        builder.AppendLine($@"  ""tenantProperty"": {Json(config.TenantProperty)},");
        builder.AppendLine($@"  ""contextTenantProperty"": {Json(config.ContextTenantProperty)},");
        builder.AppendLine($@"  ""tenantA"": {Json(config.TenantA)},");
        builder.AppendLine($@"  ""tenantB"": {Json(config.TenantB)},");
        builder.AppendLine($@"  ""provider"": {Json(config.ProviderPackage + "@" + config.ProviderVersion)},");
        builder.AppendLine($@"  ""projectReference"": {Json(projectReference)},");
        builder.AppendLine($@"  ""probedContext"": {{ ""file"": {Json(model.Context.File)}, ""line"": {model.Context.Line} }},");
        builder.AppendLine($@"  ""entities"": [");
        for (var i = 0; i < model.Entities.Count; i++)
        {
            var entity = model.Entities[i];
            var comma = i < model.Entities.Count - 1 ? "," : string.Empty;
            builder.AppendLine($@"    {{ ""name"": {Json(entity.Name)}, ""namespace"": {Json(entity.Namespace ?? string.Empty)}, ""dbSet"": {Json(entity.DbSetProperty)}, ""file"": {Json(entity.File)}, ""line"": {entity.Line} }}{comma}");
        }

        builder.AppendLine("  ]");
        builder.Append("}");
        return builder.ToString();
    }

    private static string Readme(EfModelScan model, TenantProbeConfig config, string projectReference)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Tenant-isolation probe suite");
        builder.AppendLine();
        builder.AppendLine($"Generated by `sfg tenant-probes` against `{model.Context.Name}`. This suite runs in CI so tenant isolation regresses loudly.");
        builder.AppendLine();
        builder.AppendLine("## Run");
        builder.AppendLine();
        builder.AppendLine("```bash");
        builder.AppendLine("dotnet test TenantProbes.csproj");
        builder.AppendLine("```");
        builder.AppendLine();
        builder.AppendLine("## What each probe class bites on");
        builder.AppendLine();
        builder.AppendLine("| Probe class | Probe | Fails when |");
        builder.AppendLine("| --- | --- | --- |");
        builder.AppendLine("| `CrossTenantReadProbes` | tenant B queries, tenant A's rows must stay invisible | the global tenant filter is missing, disabled, or leaks rows |");
        builder.AppendLine("| `SaveGuardProbes` | saving an entity stamped with a foreign tenant id must throw | `SaveChanges` accepts cross-tenant writes |");
        builder.AppendLine("| `PoolCheckoutProbes` | a fresh context checked out over the same options must not inherit the previous tenant's session state | tenant state is static or otherwise leaks across checkouts |");
        builder.AppendLine("| `DisabledStateFailClosedProbes` | with no tenant context set, reads must return nothing and writes must throw | the disabled state fails open (returns all tenants' rows) |");
        builder.AppendLine();
        builder.AppendLine("## Probed entities");
        builder.AppendLine();
        builder.AppendLine("| Entity | DbSet | Declared at |");
        builder.AppendLine("| --- | --- | --- |");
        foreach (var entity in model.Entities)
        {
            builder.AppendLine($"| `{entity.Name}` | `{entity.DbSetProperty}` | `{entity.File}:{entity.Line}` |");
        }

        builder.AppendLine();
        builder.AppendLine($"Target: `{Path.GetFileName(model.Context.ProjectPath)}` (referenced as `{projectReference}`), DbContext `{model.Context.Name}` (`{model.Context.File}:{model.Context.Line}`), tenant property `{config.TenantProperty}`, probe tenants `{config.TenantA}` / `{config.TenantB}`.");
        return builder.ToString();
    }

    /// <summary>Escapes a value as a C# string literal.</summary>
    private static string Literal(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var ch in value)
        {
            switch (ch)
            {
                case '\\': builder.Append(@"\\"); break;
                case '\"': builder.Append("\\\""); break;
                case '\n': builder.Append(@"\n"); break;
                case '\r': builder.Append(@"\r"); break;
                case '\t': builder.Append(@"\t"); break;
                default:
                    if (char.IsControl(ch))
                    {
                        builder.Append($"\\u{(int)ch:x4}");
                    }
                    else
                    {
                        builder.Append(ch);
                    }

                    break;
            }
        }

        builder.Append('\"');
        return builder.ToString();
    }

    /// <summary>Escapes a value as a JSON string (with surrounding quotes).</summary>
    private static string Json(string value) => "\"" + System.Text.Json.JsonEncodedText.Encode(value) + "\"";
}
