using System.Text;

namespace Sfg.Toolkit.TenantProbes;

public sealed record GeneratedFile(string Path, string Content);

public sealed record ProbeSuite(IReadOnlyList<GeneratedFile> Files, IReadOnlyList<EntityInfo> Entities);

/// <summary>
/// Generates the tenant-isolation probe suite (#58): a compilable xunit
/// project that probes the target application's tenant isolation —
/// cross-tenant reads, fail-closed saves, pool-checkout session leakage,
/// and disabled-state fail-closed behavior. Output is deterministic for a
/// given scan: byte-identical on regeneration, safe to diff and commit.
/// </summary>
public static class TenantProbeGenerator
{
    private const string Header = "// Generated by sfg tenant-probes — do not edit; regenerate instead.";
    private const string TestSdkVersion = "17.11.1";
    private const string XunitVersion = "2.9.2";
    private const string XunitRunnerVersion = "2.8.2";

    public static ProbeSuite Generate(string root, string outDir, EfModelScan model, TenantProbeConfig config)
    {
        root = Path.GetFullPath(root);
        outDir = Path.GetFullPath(outDir);

        var projectReference = Path.GetRelativePath(outDir, Path.GetFullPath(model.Context.ProjectPath))
            .Replace('\\', '/');
        var targetFramework = model.TargetFramework ?? "net8.0";
        var usings = Usings(model);

        var files = new List<GeneratedFile>
        {
            new("TenantProbes.csproj", Csproj(config, projectReference, targetFramework)),
            new("ProbeHarness.cs", Harness(model, config, usings)),
            new("CrossTenantReadProbes.cs", CrossTenantReadProbes(model, config, usings)),
            new("SaveGuardProbes.cs", SaveGuardProbes(model, config, usings)),
            new("PoolCheckoutProbes.cs", PoolCheckoutProbes(model, config, usings)),
            new("DisabledStateFailClosedProbes.cs", DisabledStateFailClosedProbes(model, config, usings)),
            new("manifest.json", Manifest(root, model, config, projectReference, targetFramework)),
            new("README.md", Readme(model, config, projectReference)),
        };

        return new ProbeSuite(files, model.Entities);
    }

    private static string[] Usings(EfModelScan model)
    {
        return model.Entities.Select(e => e.Namespace)
            .Append(model.Context.Namespace)
            .Where(ns => !string.IsNullOrWhiteSpace(ns))
            .Distinct()
            .Order(StringComparer.Ordinal)
            .Cast<string>()
            .ToArray();
    }

    private static string UsingBlock(string[] usings) =>
        usings.Length == 0 ? string.Empty : string.Join("\n", usings.Select(ns => $"using {ns};")) + "\n";

    private static string Csproj(TenantProbeConfig config, string projectReference, string targetFramework)
    {
        return $$"""
            <!-- Generated by sfg tenant-probes — do not edit; regenerate instead. -->
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>{{targetFramework}}</TargetFramework>
                <Nullable>enable</Nullable>
                <ImplicitUsings>enable</ImplicitUsings>
                <IsPackable>false</IsPackable>
              </PropertyGroup>
              <ItemGroup>
                <PackageReference Include="{{config.ProviderPackage}}" Version="{{config.ProviderVersion}}" />
                <PackageReference Include="Microsoft.NET.Test.Sdk" Version="{{TestSdkVersion}}" />
                <PackageReference Include="xunit" Version="{{XunitVersion}}" />
                <PackageReference Include="xunit.runner.visualstudio" Version="{{XunitRunnerVersion}}" />
              </ItemGroup>
              <ItemGroup>
                <ProjectReference Include="{{projectReference}}" />
              </ItemGroup>
            </Project>
            """;
    }

    private static string Harness(EfModelScan model, TenantProbeConfig config, string[] usings)
    {
        var contextType = model.Context.Name;
        return $$"""
            {{Header}}
            #nullable enable
            using Microsoft.Data.Sqlite;
            using Microsoft.EntityFrameworkCore;
            {{UsingBlock(usings)}}
            namespace TenantProbes;

            /// <summary>
            /// Test harness for the generated tenant-isolation probes. Each harness owns an
            /// in-memory SQLite database shared by every context it checks out, mirroring a
            /// context-pool checkout over one connection.
            /// </summary>
            public sealed class ProbeHarness : IDisposable
            {
                public const string TenantIdProperty = {{Literal(config.TenantProperty)}};
                public const string TenantA = {{Literal(config.TenantA)}};
                public const string TenantB = {{Literal(config.TenantB)}};

                private readonly SqliteConnection _connection;
                private readonly Microsoft.EntityFrameworkCore.DbContextOptions _options;

                public ProbeHarness()
                {
                    _connection = new SqliteConnection("Data Source=:memory:");
                    _connection.Open();
                    _options = new DbContextOptionsBuilder<{{contextType}}>()
                        .UseSqlite(_connection)
                        .Options;
                    Context = new {{contextType}}(_options);
                    Context.Database.EnsureCreated();
                }

                public {{contextType}} Context { get; }

                /// <summary>Checks out a second context over the same options and database — the pool-checkout stand-in.</summary>
                public {{contextType}} CheckoutSecond() => new(_options);

                public void Seed<TEntity>() where TEntity : class, new()
                {
                    Context.{{config.ContextTenantProperty}} = TenantA;
                    AddTenantRow<TEntity>(TenantA);
                    Context.SaveChanges();
                    Context.{{config.ContextTenantProperty}} = TenantB;
                    AddTenantRow<TEntity>(TenantB);
                    Context.SaveChanges();
                }

                /// <summary>Adds an entity of tenant <paramref name="tenant"/> to the change tracker.</summary>
                public void AddTenantRow<TEntity>(string tenant) where TEntity : class, new()
                {
                    var entity = new TEntity();
                    Context.Set<TEntity>().Add(entity);
                    Context.Entry(entity).Property(TenantIdProperty).CurrentValue = tenant;
                }

                /// <summary>Reads the tenant discriminator of a tracked entity.</summary>
                public static string? TenantIdOf(Microsoft.EntityFrameworkCore.DbContext context, object entity)
                    => context.Entry(entity).Property(TenantIdProperty).CurrentValue as string;

                public void Dispose()
                {
                    Context.Dispose();
                    _connection.Dispose();
                }
            }
            """;
    }

    private static string CrossTenantReadProbes(EfModelScan model, TenantProbeConfig config, string[] usings)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using Microsoft.EntityFrameworkCore;");
        builder.AppendLine("using Xunit;");
        builder.AppendLine(UsingBlock(usings).TrimEnd());
        builder.AppendLine();
        builder.AppendLine("namespace TenantProbes;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Tenant A asks for tenant B's rows: the global tenant filter must hide them.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public sealed class CrossTenantReadProbes");
        builder.AppendLine("{");
        foreach (var entity in model.Entities)
        {
            builder.AppendLine($@"    [Fact]");
            builder.AppendLine($@"    public async Task {entity.Name}_tenantA_rows_are_invisible_when_current_tenant_is_B()");
            builder.AppendLine($@"    {{");
            builder.AppendLine($@"        using var harness = new ProbeHarness();");
            builder.AppendLine($@"        harness.Seed<{entity.Name}>();");
            builder.AppendLine($@"        harness.Context.{config.ContextTenantProperty} = ProbeHarness.TenantB;");
            builder.AppendLine();
            builder.AppendLine($@"        var rows = await harness.Context.Set<{entity.Name}>().ToListAsync();");
            builder.AppendLine();
            builder.AppendLine($@"        var visible = Assert.Single(rows);");
            builder.AppendLine($@"        Assert.Equal(ProbeHarness.TenantB, ProbeHarness.TenantIdOf(harness.Context, visible));");
            builder.AppendLine($@"    }}");
            builder.AppendLine();
        }

        builder.Remove(builder.Length - 1, 1);
        builder.AppendLine("}");
        return builder.ToString();
    }

