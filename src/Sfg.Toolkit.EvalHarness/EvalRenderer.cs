using System.Text;

namespace Sfg.Toolkit.EvalHarness;

/// <summary>
/// Renders the eval board (#66): eval.md (the human board), eval.json (the
/// machine summary), and the committed baseline written by --update-baseline.
/// All deterministic: sorted, no timestamps, byte-identical on regeneration.
/// </summary>
public static class EvalRenderer
{
    public const string Generator = "sfg eval 0.9.0";

    public static string Markdown(EvalHarnessConfig config, EvalReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Eval board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — suite **{config.Name}**, run **{report.RunName}**, judge `{config.Judge}`.");
        builder.AppendLine();
        builder.AppendLine("Per-case evidence always accompanies aggregate scores: a regression cites the cases that moved.");
        builder.AppendLine();
        builder.AppendLine("## Metrics");
        builder.AppendLine();
        builder.AppendLine("| Stage | Metric | Observed | Threshold | Baseline | Verdict |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- |");
        foreach (var stage in config.Stages)
        {
            foreach (var metric in stage.Metrics.OrderBy(m => m, StringComparer.Ordinal))
            {
                var observed = report.Aggregates[metric];
                var (threshold, baseline) = report.GateTargets[metric];
                var regressions = report.Findings
                    .Where(f => f.Rule == "eval/baseline-regression" && f.Message.StartsWith(metric, StringComparison.Ordinal))
                    .ToArray();
                var verdict = regressions.Length > 0 ? "regressed" :
                    observed < (threshold ?? 0) ? "below threshold" :
                    baseline is not null && observed > baseline ? "improved" : "steady";
                builder.AppendLine($"| {stage.Id} | `{metric}` | {observed:0.####} | " +
                                   $"{(threshold is null ? "—" : $"{threshold:0.####}")} | " +
                                   $"{(baseline is null ? "—" : $"{baseline:0.####}")} | {verdict} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Judge agreement (against the human-labeled sample)");
        builder.AppendLine();
        builder.AppendLine($"Sample size {report.LabeledSampleSize}, judge `{config.Judge}` agrees on {report.JudgeAgrees} " +
                            $"(agreement {report.Agreement:0.####}), disagrees on {report.JudgeDisagrees}, abstains on {report.JudgeAbstains} — abstains never count as agreement.");
        if (report.JudgeDisagreementCases.Count > 0)
        {
            builder.AppendLine();
            builder.AppendLine($"Disagreements: {string.Join(", ", report.JudgeDisagreementCases.Select(id => $"`{id}`"))} — calibrate the judge or relabel the cases before its verdicts gate anything.");
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Clean run: every case of the labeled set is reported, every metric is at or above its baseline and threshold.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Evidence |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var evidence = finding.Evidence.Count == 0
                    ? "—"
                    : string.Join(" · ", finding.Evidence.Select(e => $"`{e}`"));
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {evidence} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Cases.Count} case(s), {report.Results.Count} result(s), " +
                           $"{report.Findings.Count} finding(s) — {report.Errors} error(s), {report.Warnings} warning(s). " +
                           "Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(EvalHarnessConfig config, EvalReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"suite\": {J(config.Name)},");
        builder.AppendLine($"  \"run\": {J(report.RunName)},");
        builder.AppendLine($"  \"judge\": {J(config.Judge)},");
        builder.AppendLine("  \"metrics\": {");
        var metrics = report.Aggregates.Keys.OrderBy(m => m, StringComparer.Ordinal).ToArray();
        for (var i = 0; i < metrics.Length; i++)
        {
            var metric = metrics[i];
            var (threshold, baseline) = report.GateTargets[metric];
            var comma = i < metrics.Length - 1 ? "," : string.Empty;
            builder.AppendLine($"    {J(metric)}: {{ \"observed\": {Num(report.Aggregates[metric])}, " +
                               $"\"threshold\": {(threshold is null ? "null" : Num(threshold.Value))}, " +
                               $"\"baseline\": {(baseline is null ? "null" : Num(baseline.Value))} }}{comma}");
        }

        builder.AppendLine("  },");
        builder.AppendLine($"  \"agreement\": {{ \"sample\": {report.LabeledSampleSize}, \"agrees\": {report.JudgeAgrees}, " +
                            $"\"value\": {Num(report.Agreement)}, \"abstains\": {report.JudgeAbstains} }},");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.RenderedFindings.Count; i++)
        {
            var finding = report.RenderedFindings[i];
            var comma = i < report.RenderedFindings.Count - 1 ? "," : string.Empty;
            var evidence = string.Join(", ", finding.Evidence.Select(J));
            builder.AppendLine($"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, " +
                               $"\"message\": {J(finding.Message)}, \"evidence\": [{evidence}] }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>The baseline written by --update-baseline: per-metric aggregate
    /// values plus per-case scores, so a future regression can cite exactly
    /// the cases that moved. Deterministic, ordinal-sorted, no timestamps.</summary>
    public static string BaselineJson(EvalHarnessConfig config, EvalReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"suite\": {J(config.Name)},");
        builder.AppendLine("  \"metrics\": {");
        var metrics = report.Aggregates.Keys.OrderBy(m => m, StringComparer.Ordinal).ToArray();
        for (var i = 0; i < metrics.Length; i++)
        {
            var metric = metrics[i];
            var comma = i < metrics.Length - 1 ? "," : string.Empty;
            builder.AppendLine($"    {J(metric)}: {{ \"value\": {Num(report.Aggregates[metric])}, \"cases\": {{");
            var scores = report.PerCase[metric];
            for (var j = 0; j < scores.Count; j++)
            {
                var caseComma = j < scores.Count - 1 ? "," : string.Empty;
                builder.AppendLine($"      {J(scores[j].CaseId)}: {Num(scores[j].Score)}{caseComma}");
            }

            builder.AppendLine($"    }} }}{comma}");
        }

        builder.AppendLine("  }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    internal static string Num(double value) =>
        value == Math.Floor(value) ? value.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture) + "" :
        value.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture);

    internal static string J(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }
}