using System.Text;
using System.Text.Json;

namespace Sfg.Toolkit.Cockpit;

public sealed record ShadowGeneratedFile(string Path, string Content);

public sealed record ShadowDiffSuite(IReadOnlyList<ShadowGeneratedFile> Files, IReadOnlyList<string> Routes);

/// <summary>
/// Generates the shadow-diff suite for shadow routes (#56): a compilable
/// xunit project that runs the same cases through the old and the new
/// implementation and fails loudly on any drift the route's tolerance rules
/// do not excuse. Handler declarations and case counts are recorded with
/// file:line evidence in the manifest. Deterministic: byte-identical on
/// regeneration, safe to diff and commit.
/// </summary>
public static class ShadowDiffGenerator
{
    private const string Header = "// Generated by sfg cockpit — do not edit; regenerate instead.";
    private const string TestSdkVersion = "17.11.1";
    private const string XunitVersion = "2.9.2";
    private const string XunitRunnerVersion = "2.8.2";
    private const string BaseIndent = "        ";

    public static ShadowDiffSuite Generate(
        string root,
        string outDir,
        MigrationConfig config,
        IReadOnlyList<HandlerSite> handlers)
    {
        root = Path.GetFullPath(root);
        outDir = Path.GetFullPath(outDir);

        var shadowRoutes = config.Routes.Where(r => r.Shadow).OrderBy(r => r.Id, StringComparer.Ordinal).ToList();
        if (shadowRoutes.Count == 0)
        {
            throw new InvalidOperationException(
                "no route in the table declares a shadow diff (\"shadow\": true) — nothing to generate");
        }

        var targetProject = ResolveTargetProject(root, config, handlers, shadowRoutes);
        var targetFramework = ReadTargetFramework(targetProject) ?? "net8.0";
        var projectReference = Path.GetRelativePath(outDir, Path.GetFullPath(targetProject)).Replace('\\', '/');

        var prepared = new List<PreparedShadowRoute>();
        foreach (var route in shadowRoutes)
        {
            prepared.Add(Prepare(root, route, handlers));
        }

        var files = new List<ShadowGeneratedFile>
        {
            new("ShadowDiff.csproj", Csproj(projectReference, targetFramework)),
            new("ShadowDiffHarness.cs", Harness()),
            new("RouteShadowProbes.cs", Probes(prepared)),
            new("Cases.cs", Cases(prepared)),
            new("manifest.json", Manifest(config, targetProject, projectReference, targetFramework, prepared)),
            new("README.md", Readme(prepared, projectReference)),
        };

        return new ShadowDiffSuite(files, prepared.Select(p => p.Route.Id).ToArray());
    }

    private sealed record PreparedShadowRoute(
        MigrationRoute Route,
        HandlerSite OldSite,
        HandlerSite NewSite,
        string CasesJson,
        int CaseCount);

    private static PreparedShadowRoute Prepare(string root, MigrationRoute route, IReadOnlyList<HandlerSite> handlers)
    {
        var oldSite = HandlerScanner.Require(handlers, route.Old!, "old", route.Id);
        var newSite = HandlerScanner.Require(handlers, route.New!, "new", route.Id);

        var casesPath = Path.Combine(root, route.Cases!);
        if (!File.Exists(casesPath))
        {
            throw new InvalidOperationException(
                $"route '{route.Id}': shadow cases file not found: {route.Cases} — shadow routes need \"cases\"");
        }

        var casesJson = File.ReadAllText(casesPath);
        if (casesJson.Contains("\"\"\"", StringComparison.Ordinal))
        {
            throw new InvalidOperationException(
                $"route '{route.Id}': cases file {route.Cases} contains a raw string delimiter (\"\"\") — " +
                "case inputs cannot be embedded verbatim");
        }

        int caseCount;
        try
        {
            using var document = JsonDocument.Parse(casesJson);
            if (document.RootElement.ValueKind != JsonValueKind.Array)
            {
                throw new InvalidOperationException(
                    $"route '{route.Id}': cases file {route.Cases} must be a JSON array of inputs");
            }

            caseCount = document.RootElement.GetArrayLength();
        }
        catch (JsonException exception)
        {
            throw new InvalidOperationException(
                $"route '{route.Id}': cases file {route.Cases} is not valid JSON: {exception.Message}");
        }

        if (caseCount == 0)
        {
            throw new InvalidOperationException(
                $"route '{route.Id}': cases file {route.Cases} declares no cases — a shadow diff needs at least one");
        }

        return new PreparedShadowRoute(route, oldSite, newSite, casesJson, caseCount);
    }

    private static string ResolveTargetProject(
        string root,
        MigrationConfig config,
        IReadOnlyList<HandlerSite> handlers,
        IReadOnlyList<MigrationRoute> shadowRoutes)
    {
        if (config.Project is not null)
        {
            var declared = Path.Combine(root, config.Project);
            if (!File.Exists(declared))
            {
                throw new InvalidOperationException(
                    $"route table declares project '{config.Project}' but no such project file exists under the root");
            }

            return declared;
        }

        var projects = new List<string>();
        foreach (var route in shadowRoutes)
        {
            foreach (var name in new[] { route.Old!, route.New! })
            {
                var site = HandlerScanner.Require(handlers, name, "shadow", route.Id);
                if (site.ProjectPath.Length == 0)
                {
                    throw new InvalidOperationException(
                        $"route '{route.Id}': handler '{name}' at {site.File}:{site.Line} has no project file " +
                        "above it — declare the target project with \"project\" in the route table");
                }

                projects.Add(site.ProjectPath);
            }
        }

        var distinct = projects.Distinct(StringComparer.Ordinal).OrderBy(p => p, StringComparer.Ordinal).ToList();
        if (distinct.Count == 0)
        {
            throw new InvalidOperationException(
                "no shadow route names its handlers — cannot resolve the target project");
        }

        if (distinct.Count > 1)
        {
            throw new InvalidOperationException(
                "shadow routes span more than one project (" +
                string.Join(", ", distinct.Select(Path.GetFileName)) +
                ") — declare the target project with \"project\" in the route table");
        }

        return distinct[0];
    }

    private static string? ReadTargetFramework(string projectPath)
    {
        var text = File.ReadAllText(projectPath);
        var match = System.Text.RegularExpressions.Regex.Match(
            text, "<TargetFramework>\\s*([^<\\s]+)\\s*</TargetFramework>");
        return match.Success ? match.Groups[1].Value : null;
    }

    private static string Csproj(string projectReference, string targetFramework)
    {
        return $$"""
            <!-- Generated by sfg cockpit — do not edit; regenerate instead. -->
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>{{targetFramework}}</TargetFramework>
                <Nullable>enable</Nullable>
                <ImplicitUsings>enable</ImplicitUsings>
                <IsPackable>false</IsPackable>
              </PropertyGroup>
              <ItemGroup>
                <PackageReference Include="Microsoft.NET.Test.Sdk" Version="{{TestSdkVersion}}" />
                <PackageReference Include="xunit" Version="{{XunitVersion}}" />
                <PackageReference Include="xunit.runner.visualstudio" Version="{{XunitRunnerVersion}}" />
              </ItemGroup>
              <ItemGroup>
                <ProjectReference Include="{{projectReference}}" />
              </ItemGroup>
            </Project>
            """;
    }

    private static string Harness()
    {
        return """
            // Generated by sfg cockpit — do not edit; regenerate instead.
            #nullable enable
            using System.Text.Json;

            namespace ShadowDiff;

            /// <summary>
            /// Shadow-diff harness: runs the same case through the old and the new
            /// implementation and fails loudly on any drift the route's tolerance
            /// rules do not excuse. Tolerances are keyed by leaf field name at any
            /// depth; ignored fields are skipped at any depth.
            /// </summary>
            public static class ShadowDiffHarness
            {
                public static void DiffRoute(
                    string routeId,
                    Func<string, string> old,
                    Func<string, string> current,
                    string casesJson,
                    string[] ignored,
                    (string Field, decimal Tolerance)[] numeric)
                {
                    using var cases = System.Text.Json.JsonDocument.Parse(casesJson);
                    if (cases.RootElement.ValueKind != JsonValueKind.Array)
                    {
                        throw new InvalidOperationException($"route '{routeId}': cases must be a JSON array of inputs");
                    }

                    var index = 0;
                    foreach (var input in cases.RootElement.EnumerateArray())
                    {
                        var inputJson = input.GetRawText();
                        using var oldOutput = System.Text.Json.JsonDocument.Parse(old(inputJson));
                        using var newOutput = System.Text.Json.JsonDocument.Parse(current(inputJson));
                        Compare(routeId, index, "$", oldOutput.RootElement, newOutput.RootElement, ignored, numeric);
                        index++;
                    }
                }

                private static void Compare(
                    string routeId,
                    int caseIndex,
                    string path,
                    System.Text.Json.JsonElement oldElement,
                    System.Text.Json.JsonElement newElement,
                    string[] ignored,
                    (string Field, decimal Tolerance)[] numeric)
                {
                    if (oldElement.ValueKind != newElement.ValueKind)
                    {
                        throw Drift(
                            routeId, caseIndex, path,
                            $"kind mismatch — old {oldElement.ValueKind} vs new {newElement.ValueKind}",
                            oldElement.GetRawText(), newElement.GetRawText());
                    }

                    switch (oldElement.ValueKind)
                    {
                        case JsonValueKind.Object:
                            foreach (var property in oldElement.EnumerateObject())
                            {
                                if (Array.IndexOf(ignored, property.Name) >= 0)
                                {
                                    continue;
                                }

                                if (!newElement.TryGetProperty(property.Name, out var newChild))
                                {
                                    throw Drift(routeId, caseIndex, $"{path}.{property.Name}",
                                        "property missing in the new output",
                                        property.Value.GetRawText(), "<absent>");
                                }

                                Compare(routeId, caseIndex, $"{path}.{property.Name}",
                                    property.Value, newChild, ignored, numeric);
                            }

                            foreach (var property in newElement.EnumerateObject())
                            {
                                if (Array.IndexOf(ignored, property.Name) >= 0)
                                {
                                    continue;
                                }

                                if (!oldElement.TryGetProperty(property.Name, out _))
                                {
                                    throw Drift(routeId, caseIndex, $"{path}.{property.Name}",
                                        "property present only in the new output",
                                        "<absent>", property.Value.GetRawText());
                                }
                            }

                            break;

                        case JsonValueKind.Array:
                            if (oldElement.GetArrayLength() != newElement.GetArrayLength())
                            {
                                throw Drift(routeId, caseIndex, path,
                                    $"length mismatch — old {oldElement.GetArrayLength()} vs new {newElement.GetArrayLength()}",
                                    oldElement.GetRawText(), newElement.GetRawText());
                            }

                            for (var i = 0; i < oldElement.GetArrayLength(); i++)
                            {
                                Compare(routeId, caseIndex, $"{path}[{i}]",
                                    oldElement[i], newElement[i], ignored, numeric);
                            }

                            break;

                        case JsonValueKind.Number:
                        {
                            var field = LeafField(path);
                            decimal tolerance = -1;
                            var tolerated = false;
                            foreach (var rule in numeric)
                            {
                                if (string.Equals(rule.Field, field, StringComparison.Ordinal))
                                {
                                    tolerance = rule.Tolerance;
                                    tolerated = true;
                                    break;
                                }
                            }

                            if (tolerated)
                            {
                                if (Math.Abs(oldElement.GetDecimal() - newElement.GetDecimal()) > tolerance)
                                {
                                    throw Drift(routeId, caseIndex, path,
                                        $"outside numeric tolerance {tolerance}",
                                        oldElement.GetRawText(), newElement.GetRawText());
                                }
                            }
                            else if (oldElement.GetRawText() != newElement.GetRawText())
                            {
                                throw Drift(routeId, caseIndex, path, "numbers differ",
                                    oldElement.GetRawText(), newElement.GetRawText());
                            }

                            break;
                        }

                        case JsonValueKind.String:
                            if (oldElement.GetString() != newElement.GetString())
                            {
                                throw Drift(routeId, caseIndex, path, "strings differ",
                                    oldElement.GetString() ?? "", newElement.GetString() ?? "");
                            }

                            break;

                        case JsonValueKind.True:
                        case JsonValueKind.False:
                            if (oldElement.GetBoolean() != newElement.GetBoolean())
                            {
                                throw Drift(routeId, caseIndex, path, "booleans differ",
                                    oldElement.GetRawText(), newElement.GetRawText());
                            }

                            break;

                        default:
                            if (oldElement.GetRawText() != newElement.GetRawText())
                            {
                                throw Drift(routeId, caseIndex, path, "values differ",
                                    oldElement.GetRawText(), newElement.GetRawText());
                            }

                            break;
                    }
                }

                private static string LeafField(string path)
                {
                    var leaf = path;
                    var dot = leaf.LastIndexOf('.');
                    if (dot >= 0)
                    {
                        leaf = leaf[(dot + 1)..];
                    }

                    var bracket = leaf.LastIndexOf('[');
                    if (bracket >= 0)
                    {
                        leaf = leaf[..bracket];
                    }

                    return leaf;
                }

                private static Exception Drift(
                    string routeId, int caseIndex, string path, string detail, string oldText, string newText)
                {
                    return new InvalidOperationException(
                        $"SHADOW DRIFT on route '{routeId}' case #{caseIndex}: {path} — {detail} " +
                        $"(old: {oldText}, new: {newText})");
                }
            }
            """;
    }

    private static string Probes(IReadOnlyList<PreparedShadowRoute> prepared)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using Xunit;");
        foreach (var ns in prepared.SelectMany(p => new[] { p.OldSite.Namespace, p.NewSite.Namespace })
                     .Where(ns => !string.IsNullOrWhiteSpace(ns))
                     .Distinct()
                     .Order(StringComparer.Ordinal))
        {
            builder.AppendLine($"using {ns};");
        }

        builder.AppendLine();
        builder.AppendLine("namespace ShadowDiff;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Shadow-diff probes: the same cases run through the old and the new");
        builder.AppendLine("/// implementation of each shadow route. Drift beyond the route's declared");
        builder.AppendLine("/// tolerance fails the suite — the strangler fig only earns a route when");
        builder.AppendLine("/// old and new agree.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public sealed class RouteShadowProbes");
        builder.AppendLine("{");
        for (var i = 0; i < prepared.Count; i++)
        {
            var route = prepared[i].Route;
            var name = Pascal(route.Id);
            var ignored = route.Tolerance is null || route.Tolerance.Ignore.Count == 0
                ? "Array.Empty<string>()"
                : "new[] { " + string.Join(", ", route.Tolerance.Ignore.Select(v => $"\"{v}\"")) + " }";
            var numeric = route.Tolerance is null || route.Tolerance.Numeric.Count == 0
                ? "Array.Empty<(string, decimal)>()"
                : "new[] { " + string.Join(", ", route.Tolerance.Numeric
                      .OrderBy(kv => kv.Key, StringComparer.Ordinal)
                      .Select(kv => $"(\"{kv.Key}\", {kv.Value.ToString(System.Globalization.CultureInfo.InvariantCulture)}m)")) + " }";

            if (i > 0)
            {
                builder.AppendLine();
            }

            builder.AppendLine("    [Fact]");
            builder.AppendLine($"    public void {name}_old_and_new_stay_within_tolerance()");
            builder.AppendLine("    {");
            builder.AppendLine("        ShadowDiffHarness.DiffRoute(");
            builder.AppendLine($"            \"{route.Id}\",");
            builder.AppendLine($"            input => new {route.Old}().{route.Method}(input),");
            builder.AppendLine($"            input => new {route.New}().{route.Method}(input),");
            builder.AppendLine($"            Cases.{name},");
            builder.AppendLine($"            {ignored},");
            builder.AppendLine($"            {numeric});");
            builder.AppendLine("    }");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Cases(IReadOnlyList<PreparedShadowRoute> prepared)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace ShadowDiff;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Shadow-diff case inputs, embedded verbatim from the application's");
        builder.AppendLine("/// case files. Regenerate with sfg cockpit; do not edit.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public static class Cases");
        builder.AppendLine("{");
        for (var i = 0; i < prepared.Count; i++)
        {
            if (i > 0)
            {
                builder.AppendLine();
            }

            builder.AppendLine($"    public const string {Pascal(prepared[i].Route.Id)} = \"\"\"");
            foreach (var rawLine in prepared[i].CasesJson.Replace("\r\n", "\n").Split('\n'))
            {
                builder.AppendLine(rawLine.Length == 0 ? string.Empty : BaseIndent + rawLine);
            }

            builder.AppendLine("        \"\"\";");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Manifest(
        MigrationConfig config,
        string targetProjectPath,
        string projectReference,
        string targetFramework,
        IReadOnlyList<PreparedShadowRoute> prepared)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {Json(CockpitRenderer.Generator)},");
        builder.AppendLine($"  \"targetProject\": {Json(Path.GetFileName(targetProjectPath))},");
        builder.AppendLine($"  \"targetFramework\": {Json(targetFramework)},");
        builder.AppendLine($"  \"projectReference\": {Json(projectReference)},");
        builder.AppendLine($"  \"routeMethod\": {Json(config.RouteMethod)},");
        builder.AppendLine("  \"shadowRoutes\": [");
        for (var i = 0; i < prepared.Count; i++)
        {
            var p = prepared[i];
            var comma = i < prepared.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"id\": {Json(p.Route.Id)}, " +
                              $"\"old\": {{ \"handler\": {Json(p.OldSite.Name)}, \"file\": {Json(p.OldSite.File)}, \"line\": {p.OldSite.Line} }}, " +
                              $"\"new\": {{ \"handler\": {Json(p.NewSite.Name)}, \"file\": {Json(p.NewSite.File)}, \"line\": {p.NewSite.Line} }}, " +
                              $"\"method\": {Json(p.Route.Method)}, \"cases\": {Json(p.Route.Cases ?? string.Empty)}, \"caseCount\": {p.CaseCount}, " +
                              $"\"ignored\": [{Join(p.Route.Tolerance?.Ignore)}], " +
                              $"\"numeric\": [{JoinNumeric(p.Route.Tolerance?.Numeric)}] }}{comma}");
        }

        builder.AppendLine("  ]");
        builder.Append("}");
        return builder.ToString();
    }

    private static string Join(IReadOnlyList<string>? values)
    {
        if (values is null || values.Count == 0)
        {
            return string.Empty;
        }

        return string.Join(", ", values.OrderBy(v => v, StringComparer.Ordinal).Select(Json));
    }

    private static string JoinNumeric(IReadOnlyDictionary<string, decimal>? numeric)
    {
        if (numeric is null || numeric.Count == 0)
        {
            return string.Empty;
        }

        return string.Join(", ", numeric
            .OrderBy(kv => kv.Key, StringComparer.Ordinal)
            .Select(kv => $"{{ \"field\": {Json(kv.Key)}, \"tolerance\": {kv.Value.ToString(System.Globalization.CultureInfo.InvariantCulture)} }}"));
    }

    private static string Readme(IReadOnlyList<PreparedShadowRoute> prepared, string projectReference)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Shadow-diff suite");
        builder.AppendLine();
        builder.AppendLine("Generated by `sfg cockpit` against the route table's shadow routes. " +
                          "This suite runs in CI so old and new implementations cannot drift apart silently.");
        builder.AppendLine();
        builder.AppendLine("## Run");
        builder.AppendLine();
        builder.AppendLine("```bash");
        builder.AppendLine("dotnet test ShadowDiff.csproj");
        builder.AppendLine("```");
        builder.AppendLine();
        builder.AppendLine("## What each probe bites on");
        builder.AppendLine();
        builder.AppendLine("| Probe | Old handler | New handler | Cases | Ignored fields | Numeric tolerances |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- |");
        foreach (var p in prepared)
        {
            var ignored = p.Route.Tolerance is null || p.Route.Tolerance.Ignore.Count == 0
                ? "—"
                : string.Join(", ", p.Route.Tolerance.Ignore);
            var numeric = p.Route.Tolerance is null || p.Route.Tolerance.Numeric.Count == 0
                ? "—"
                : string.Join(", ", p.Route.Tolerance.Numeric
                    .OrderBy(kv => kv.Key, StringComparer.Ordinal)
                    .Select(kv => $"{kv.Key} ± {kv.Value.ToString(System.Globalization.CultureInfo.InvariantCulture)}"));
            builder.AppendLine(
                $"| `{p.Route.Id}_old_and_new_stay_within_tolerance` | `{p.OldSite.Name}` (`{p.OldSite.File}:{p.OldSite.Line}`) | " +
                $"`{p.NewSite.Name}` (`{p.NewSite.File}:{p.NewSite.Line}`) | {p.CaseCount} (`{p.Route.Cases}`) | {ignored} | {numeric} |");
        }

        builder.AppendLine();
        builder.AppendLine($"Target: `{projectReference}`. A failure prefixed `SHADOW DRIFT on route '...'` names the route, " +
                          "the case, the drifting path, and both values — fix the implementation or widen the declared tolerance; never the probe.");
        return builder.ToString();
    }

    private static string Pascal(string id)
    {
        var parts = id.Split(new[] { '.', '-', '_', '/', ' ' }, StringSplitOptions.RemoveEmptyEntries);
        var builder = new StringBuilder();
        foreach (var part in parts)
        {
            builder.Append(char.ToUpperInvariant(part[0]));
            if (part.Length > 1)
            {
                builder.Append(part[1..]);
            }
        }

        return builder.ToString();
    }

    private static string Json(string value) => "\"" + System.Text.Json.JsonEncodedText.Encode(value) + "\"";
}
