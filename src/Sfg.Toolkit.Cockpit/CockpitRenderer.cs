using System.Text;
using Sfg.Toolkit.Core.Drawio;

namespace Sfg.Toolkit.Cockpit;

/// <summary>
/// Renders the strangler-fig cockpit outputs (#56): cockpit.md (the human
/// board), cockpit.json (the machine summary), and cockpit.drawio (the state
/// map, in the book's diagram conventions). All deterministic: sorted,
/// no timestamps, byte-identical on regeneration.
/// </summary>
public static class CockpitRenderer
{
    public const string Generator = "sfg cockpit 0.5.0";

    public static string Markdown(CockpitReport report, MigrationConfig config)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Strangler-fig migration cockpit");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — routing-seam coverage, shadow-diff wiring, and the sunset tripwire, with file:line evidence.");
        builder.AppendLine();
        builder.AppendLine("## Routes");
        builder.AppendLine();
        builder.AppendLine("| Route | State | Wired at | Old handler | New handler | Traffic (oldest first) | Retirement threshold | Sunset verdict |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- |");
        foreach (var view in report.Routes)
        {
            var route = config.Routes.First(r => string.Equals(r.Id, view.Id, StringComparison.Ordinal));
            var oldHandler = route.Old ?? "—";
            var newHandler = route.New ?? "—";
            var traffic = view.Traffic.Count == 0 ? "—" : string.Join(", ", view.Traffic);
            var verdict = view.SunsetWindowOpen
                ? $"window open at threshold {view.Threshold} over {view.SunsetPeriods} periods"
                : view.State == "strangled" && view.Traffic.Count < view.SunsetPeriods
                    ? $"insufficient history ({view.Traffic.Count}/{view.SunsetPeriods} periods)"
                    : "—";
            builder.AppendLine(
                $"| `{view.Id}` | {view.State} | {(view.Wired ? $"`{view.Evidence}`" : "**unwired**")} | " +
                $"`{oldHandler}` | `{newHandler}` | {traffic} | {view.Threshold} | {verdict} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("No findings — every declared route is wired, no undeclared route is wired, and no strangled route contradicts its traffic history.");
        }
        else
        {
            foreach (var finding in report.Findings)
            {
                builder.AppendLine($"- **{finding.Severity}** `{finding.Rule}` (route `{finding.RouteId}`): {finding.Message} (`{finding.Evidence}`)");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Routes.Count} routes ({report.Routes.Count(r => r.State == "todo")} todo, " +
                          $"{report.Routes.Count(r => r.State == "strangling")} strangling, {report.Routes.Count(r => r.State == "strangled")} strangled), " +
                          $"{report.Findings.Count} findings ({report.Errors} errors, {report.Warnings} warnings).");
        return builder.ToString();
    }

    public static string Json(CockpitReport report, MigrationConfig config)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {Json(Generator)},");
        builder.AppendLine($"  \"routeMethod\": {Json(config.RouteMethod)},");
        builder.AppendLine("  \"routes\": [");
        for (var i = 0; i < report.Routes.Count; i++)
        {
            var view = report.Routes[i];
            var route = config.Routes.First(r => string.Equals(r.Id, view.Id, StringComparison.Ordinal));
            var comma = i < report.Routes.Count - 1 ? "," : string.Empty;
            var traffic = view.Traffic.Count == 0 ? string.Empty : string.Join(", ", view.Traffic);
            builder.AppendLine($"    {{ \"id\": {Json(view.Id)}, \"state\": {Json(view.State)}, \"wired\": {(view.Wired ? "true" : "false")}, " +
                              $"\"wiredAt\": {Json(view.Evidence)}, \"old\": {Json(route.Old ?? string.Empty)}, \"new\": {Json(route.New ?? string.Empty)}, " +
                              $"\"shadow\": {(view.Shadow ? "true" : "false")}, \"traffic\": [{traffic}], \"retirementThreshold\": {view.Threshold}, " +
                              $"\"sunsetPeriods\": {view.SunsetPeriods}, \"sunsetWindowOpen\": {(view.SunsetWindowOpen ? "true" : "false")} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.Findings.Count; i++)
        {
            var finding = report.Findings[i];
            var comma = i < report.Findings.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"rule\": {Json(finding.Rule)}, \"severity\": {Json(finding.Severity)}, " +
                              $"\"route\": {Json(finding.RouteId)}, \"message\": {Json(finding.Message)}, \"evidence\": {Json(finding.Evidence)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.Append("}");
        return builder.ToString();
    }

    public static string Drawio(CockpitReport report)
    {
        var doc = new DrawioDocument();
        var columns = new Dictionary<string, double>
        {
            ["todo"] = 40,
            ["strangling"] = 340,
            ["strangled"] = 640,
        };
        var rows = new Dictionary<string, int>();
        var fired = report.Findings
            .Where(f => f.Rule is "migration/sunset-window" or "migration/strangle-unfinished")
            .Select(f => f.RouteId)
            .ToHashSet(StringComparer.Ordinal);

        doc.AddNode("title", "Strangler-fig migration cockpit<br/>todo | strangling | strangled", "text;html=1;align=center;fontSize=16;fontStyle=1", 40, 20, 820, 40);
        foreach (var view in report.Routes)
        {
            var x = columns[view.State];
            var y = 80 + rows.GetValueOrDefault(view.State) * 90;
            rows[view.State] = rows.GetValueOrDefault(view.State) + 1;

            var (fill, stroke) = view.State switch
            {
                "strangled" => ("#d5e8d4", "#82b366"),
                "strangling" => ("#fff2cc", "#d6b656"),
                _ => ("#f5f5f5", "#666666"),
            };
            var style = $"rounded=1;whiteSpace=wrap;html=1;fillColor={fill};strokeColor={(fired.Contains(view.Id) ? "#b85450" : stroke)}";
            if (fired.Contains(view.Id))
            {
                style += ";dashed=1";
            }

            var tripwire = fired.Contains(view.Id)
                ? "<br/><b>tripwire fired</b>"
                : view.Wired ? string.Empty : "<br/><b>unwired</b>";
            doc.AddNode(
                $"route-{view.Id}",
                $"{System.Net.WebUtility.HtmlEncode(view.Id)}<br/>state: {view.State}{tripwire}",
                style,
                x,
                y,
                240,
                70);
        }

        return doc.ToXml(1169, 826, "Cockpit", "cockpit");
    }

    private static string Json(string value) => "\"" + System.Text.Json.JsonEncodedText.Encode(value) + "\"";
}
