using System.Text;

namespace Sfg.Toolkit.DoraMetrics;

/// <summary>
/// Renders the DORA board (#68): dora.md (the human board), dora.json (the
/// machine summary), and dora-definitions.json — the versioned definitions
/// file the series is measured against. Deterministic: ordinal order
/// everywhere, no timestamps of the run, byte-identical on regeneration.
/// </summary>
public static class DoraRenderer
{
    public const string Generator = "sfg dora 0.10.0";

    public const string DefinitionVersion = "dora-definitions-v1";

    public static string Markdown(DoraConfig config, DoraEventsExport export, DoraReport report)
    {
        var period = config.Period switch
        {
            DoraPeriod.Day => "day",
            DoraPeriod.Month => "month",
            _ => "week",
        };

        var builder = new StringBuilder();
        builder.AppendLine("# DORA four-key board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — {report.Deployments.Count} deployment(s) " +
                           $"({report.Changes.Count} change(s), {report.Builds.Count} build(s), {report.Failures.Count} failure(s)) " +
                           $"from `{export.FileName}`" +
                           (report.Repository is null ? string.Empty : $" ({report.Repository}") +
                           (report.Window is null ? string.Empty : $", window {report.Window}") +
                           (report.Repository is null ? string.Empty : ")") + ".");
        builder.AppendLine();
        builder.AppendLine($"Four keys as trends, not scores: the series below is measured against definition version `{DefinitionVersion}` — " +
                           "the versioned definitions file is written next to this board.");
        builder.AppendLine();

        builder.AppendLine("## Joins");
        builder.AppendLine();
        builder.AppendLine("Every join the four keys depend on, verified against the export — never observed:");
        builder.AppendLine();
        builder.AppendLine("| Join | Verified | What it proves | Rule |");
        builder.AppendLine("| --- | --- | --- | --- |");
        foreach (var join in report.Joins)
        {
            builder.AppendLine($"| {join.Join} | {join.Verified}/{join.Total} | {join.Description} | {Rules(join.Rule)} |");
        }

        builder.AppendLine();
        builder.AppendLine($"## Time series ({period})");
        builder.AppendLine();
        builder.AppendLine("| Period | Deployments | Changes shipped | Lead time (h) | Failure rate | MTTR (h) |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- |");
        foreach (var row in report.Series)
        {
            builder.AppendLine($"| {row.Period} | {row.Deployments} | {row.Changes} | {Hours(row.LeadTimeHours)} | " +
                               $"{row.ChangeFailureRate.ToString("0.0", System.Globalization.CultureInfo.InvariantCulture)}% | {Hours(row.MttrHours)} |");
        }

        builder.AppendLine();
        if (report.ExcludedDeployments.Count == 0)
        {
            builder.AppendLine("Re-runs excluded from the counts: none — every deployment is a distinct release of its environment.");
        }
        else
        {
            builder.AppendLine("Re-runs excluded from the counts: " +
                               string.Join(", ", report.ExcludedDeployments.Select(id => $"`{id}`")) +
                               " — same environment, same target sha, flagged `dora/re-run-mislabeled`.");
        }

        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Clean export: every join resolves, every deployment was built green, every failure's restore is evidenced, and no re-run is mislabeled as a new deployment.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Evidence |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var evidence = finding.Evidence.Count == 0
                    ? "—"
                    : string.Join(" · ", finding.Evidence.Select(e => $"`{e}`"));
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {evidence} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.Deployments.Count} deployment(s) ({report.ExcludedDeployments.Count} re-run(s) excluded), " +
                           $"{report.Changes.Count} change(s), {report.Builds.Count} build(s), {report.Failures.Count} failure(s); " +
                           $"{report.Joins.Count} join(s) verified, {report.Series.Count} period(s) trended — " +
                           $"{report.Findings.Count} finding(s) — {report.Errors} error(s), {report.Warnings} warning(s). " +
                           "Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(DoraConfig config, DoraEventsExport export, DoraReport report)
    {
        var period = config.Period switch
        {
            DoraPeriod.Day => "day",
            DoraPeriod.Month => "month",
            _ => "week",
        };

        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"definitionVersion\": {J(DefinitionVersion)},");
        builder.AppendLine($"  \"events\": {J(export.FileName)},");
        builder.AppendLine($"  \"period\": {J(period)},");
        if (report.Repository is not null)
        {
            builder.AppendLine($"  \"repository\": {J(report.Repository)},");
        }

        if (report.Window is not null)
        {
            builder.AppendLine($"  \"window\": {J(report.Window)},");
        }

        builder.AppendLine($"  \"counts\": {{ \"deployments\": {report.Deployments.Count}, \"changes\": {report.Changes.Count}, " +
                           $"\"builds\": {report.Builds.Count}, \"failures\": {report.Failures.Count} }},");
        var excluded = string.Join(", ", report.ExcludedDeployments.Select(J));
        builder.AppendLine($"  \"excludedDeployments\": [{excluded}],");
        builder.AppendLine("  \"joins\": [");
        for (var i = 0; i < report.Joins.Count; i++)
        {
            var join = report.Joins[i];
            var comma = i < report.Joins.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"join\": {J(join.Join)}, \"verified\": {join.Verified}, \"total\": {join.Total}, " +
                               $"\"rule\": {J(join.Rule)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"series\": [");
        for (var i = 0; i < report.Series.Count; i++)
        {
            var row = report.Series[i];
            var comma = i < report.Series.Count - 1 ? "," : string.Empty;
            builder.AppendLine($"    {{ \"period\": {J(row.Period)}, \"deployments\": {row.Deployments}, " +
                               $"\"changes\": {row.Changes}, \"leadTimeHours\": {HoursJ(row.LeadTimeHours)}, " +
                               $"\"changeFailureRate\": {Rate(row.ChangeFailureRate)}, \"mttrHours\": {HoursJ(row.MttrHours)} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.RenderedFindings.Count; i++)
        {
            var finding = report.RenderedFindings[i];
            var comma = i < report.RenderedFindings.Count - 1 ? "," : string.Empty;
            var evidence = string.Join(", ", finding.Evidence.Select(J));
            builder.AppendLine($"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, " +
                               $"\"message\": {J(finding.Message)}, \"evidence\": [{evidence}] }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>The versioned definitions file: the four keys, the joins they
    /// depend on, the failure taxonomy, the re-run rule, and the periods —
    /// the contract a series is meaningless without. Byte-identical on every
    /// regeneration; committed next to the export it defines.</summary>
    public static string DefinitionsJson()
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"version\": {J(DefinitionVersion)},");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine("  \"input\": \"a recorded events export (deployments, changes, builds, failures) — the extractor reads the export and never calls an API live\",");
        builder.AppendLine("  \"keys\": {");
        builder.AppendLine($"    \"deployment-frequency\": {J("deployments per period; a re-run of the same environment at the same target sha is flagged and excluded")},");
        builder.AppendLine($"    \"lead-time-for-changes\": {J("median hours from change merged to the first deployment shipping it, 1 decimal")},");
        builder.AppendLine($"    \"change-failure-rate\": {J("verified failures detected in the period over deployments in the period, percent, 1 decimal")},");
        builder.AppendLine($"    \"mean-time-to-restore\": {J("median hours from failure detected to restored, 1 decimal")}");
        builder.AppendLine("  },");
        builder.AppendLine("  \"joins\": {");
        builder.AppendLine($"    \"deployment-to-change\": {J("a deployment lists the PRs its compare range says it ships; each must resolve to a change merged no later than the deployment (dora/dangling-join, dora/temporal-join-violation)")},");
        builder.AppendLine($"    \"deployment-to-build\": {J("each deployment's target sha must be observed by a successful CI run (dora/unbuilt-deployment)")},");
        builder.AppendLine($"    \"change-to-build\": {J("each merged change's merge sha must be observed by a CI run (dora/change-without-build)")},");
        builder.AppendLine($"    \"change-to-deployment\": {J("each merged change must be shipped by some deployment (dora/unshipped-change)")},");
        builder.AppendLine($"    \"failure-to-deployment\": {J("each failure must name an existing deployment (dora/dangling-failure-join)")},");
        builder.AppendLine($"    \"failure-to-restore-evidence\": {J("each failure's mode must be in the taxonomy and its evidence must check out (dora/unknown-failure-mode, dora/unevidenced-failure, dora/restore-before-detection)")}");
        builder.AppendLine("  },");
        builder.AppendLine("  \"taxonomy\": {");
        builder.AppendLine($"    \"revert\": {J("service restored by reverting the change; evidence: revertPr — a change merged inside the incident window")},");
        builder.AppendLine($"    \"rollback\": {J("service restored by rolling back to an earlier deployment of a different target sha; evidence: rollbackTo")},");
        builder.AppendLine($"    \"hotfix\": {J("service restored by shipping a fix forward; evidence: hotfixPr — a change merged inside the incident window")}");
        builder.AppendLine("  },");
        builder.AppendLine($"  \"re-run-rule\": {J("two deployments of the same environment at the same target sha are one deployment: the later row is a re-run mislabeled as a new deployment — flagged (dora/re-run-mislabeled) and excluded from every count")},");
        builder.AppendLine($"  \"periods\": {J("day (yyyy-MM-dd), week (ISO week, keyed by its Monday), month (yyyy-MM); a period appears in the series when it has at least one deployment")},");
        builder.AppendLine($"  \"trend-policy\": {J("trends, not scores: the series carries this definition version, never a benchmark label")}");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Rules(string rule) => string.Join(", ", rule.Split(", ").Select(r => $"`{r}`"));

    private static string Hours(double? value) =>
        value is null
            ? "—"
            : value.Value.ToString("0.0", System.Globalization.CultureInfo.InvariantCulture);

    private static string HoursJ(double? value) =>
        value is null
            ? "null"
            : value.Value.ToString("0.0", System.Globalization.CultureInfo.InvariantCulture);

    private static string Rate(double value) => value.ToString("0.0", System.Globalization.CultureInfo.InvariantCulture);

    private static string J(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < ' ' => $"\\u{(int)c:x4}",
                _ => c.ToString(),
            });
        }

        builder.Append('"');
        return builder.ToString();
    }
}

