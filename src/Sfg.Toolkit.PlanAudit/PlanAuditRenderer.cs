using System.Text;

namespace Sfg.Toolkit.PlanAudit;

/// <summary>
/// Renders the plan-conformance board (#64): plan-audit.md (the human board)
/// and plan-audit.json (the machine summary). All deterministic: sorted,
/// no timestamps, byte-identical on regeneration.
/// </summary>
public static class PlanAuditRenderer
{
    public const string Generator = "sfg plan-audit 0.7.0";

    public static string Markdown(PlanAuditConfig config, PlanAuditReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Plan-conformance audit board");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{Generator}` — the approved spec diff reconciled against the generated code diff, with line anchors on both sides.");
        builder.AppendLine();
        builder.AppendLine("Advisory by default: findings report the discrepancy; `--strict` exits non-zero on error-severity findings.");
        builder.AppendLine();
        builder.AppendLine("## Approved spec change (the intent)");
        builder.AppendLine();
        builder.AppendLine("| Spec file | Anchor | Mapped code area |");
        builder.AppendLine("| --- | --- | --- |");
        foreach (var spec in report.SpecFiles)
        {
            var map = config.SpecMapFor(spec.Path);
            var area = map is null ? "— (unmapped)" : $"`{map.Code}/`";
            var flag = spec.IsNew ? " (new)" : spec.IsDeleted ? " (deleted)" : string.Empty;
            builder.AppendLine($"| `{spec.Path}`{flag} | `{spec.AddedLine}` | {area} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Generated change (the implementation)");
        builder.AppendLine();
        builder.AppendLine("| Code file | Anchor | Spec area |");
        builder.AppendLine("| --- | --- | --- |");
        foreach (var code in report.CodeFiles)
        {
            var map = config.CodeMapFor(code.Path);
            var area = map is null ? "— (unmapped)" : $"`{map.Spec}/`";
            var flag = code.IsNew ? " (new)" : code.IsDeleted ? " (deleted)" : string.Empty;
            builder.AppendLine($"| `{code.Path}`{flag} | `{code.AddedLine}` | {area} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Matches");
        builder.AppendLine();
        if (report.Matches.Count == 0)
        {
            builder.AppendLine("No spec change was reconciled to a code change.");
        }
        else
        {
            builder.AppendLine("| Spec anchor | Code anchor | Provenance | Note |");
            builder.AppendLine("| --- | --- | --- | --- |");
            foreach (var match in report.Matches)
            {
                var note = string.IsNullOrEmpty(match.Note) ? "—" : match.Note;
                builder.AppendLine(
                    $"| `{match.SpecFile}:{match.SpecLine}` | `{match.CodeFile}:{match.CodeLine}` | {match.Provenance} | {note} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("Machine matches come from the declared spec-to-code coverage map. Semantic matches are externally produced (an LLM pass is the expected producer) and are accepted only with valid anchors on both sides — always labeled, never silent.");
        builder.AppendLine();
        builder.AppendLine("## Findings");
        builder.AppendLine();
        if (report.Findings.Count == 0)
        {
            builder.AppendLine("✅ Conformant: every approved spec change has a generated change, and every generated change has a spec basis.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Finding | Spec anchor | Code anchor |");
            builder.AppendLine("| --- | --- | --- | --- | --- |");
            foreach (var finding in report.RenderedFindings)
            {
                var spec = finding.SpecFile is null ? "—" : $"`{finding.SpecFile}:{finding.SpecLine}`";
                var code = finding.CodeFile is null ? "—" : $"`{finding.CodeFile}:{finding.CodeLine}`";
                builder.AppendLine($"| `{finding.Rule}` | {finding.Severity} | {finding.Message} | {spec} | {code} |");
            }

            if (report.Findings.Count > report.RenderedFindings.Count)
            {
                builder.AppendLine();
                builder.AppendLine($"…and {report.Findings.Count - report.RenderedFindings.Count} more (raise `maxFindings` beyond {report.Cap} to see all).");
            }
        }

        builder.AppendLine();
        builder.AppendLine($"Summary: {report.SpecFiles.Count} spec change(s), {report.CodeFiles.Count} code change(s), " +
                          $"{report.Matches.Count} match(es), {report.Findings.Count} finding(s) — " +
                          $"{report.Errors} error(s), {report.Warnings} warning(s). Advisory: exit 0; `--strict` exits 1 on errors.");
        return builder.ToString();
    }

    public static string Json(PlanAuditConfig config, PlanAuditReport report)
    {
        var builder = new StringBuilder();
        builder.AppendLine("{");
        builder.AppendLine($"  \"generator\": {J(Generator)},");
        builder.AppendLine($"  \"specFiles\": [");
        AppendFiles(builder, report.SpecFiles, f => config.SpecMapFor(f.Path)?.Code);
        builder.AppendLine("  ],");
        builder.AppendLine($"  \"codeFiles\": [");
        AppendFiles(builder, report.CodeFiles, f => config.CodeMapFor(f.Path)?.Spec);
        builder.AppendLine("  ],");
        builder.AppendLine("  \"matches\": [");
        for (var i = 0; i < report.Matches.Count; i++)
        {
            var match = report.Matches[i];
            var comma = i < report.Matches.Count - 1 ? "," : string.Empty;
            var note = match.Note is null ? "null" : J(match.Note);
            builder.AppendLine(
                $"    {{ \"spec\": {J($"{match.SpecFile}:{match.SpecLine}")}, \"code\": {J($"{match.CodeFile}:{match.CodeLine}")}, \"provenance\": {J(match.Provenance)}, \"note\": {note} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine("  \"findings\": [");
        for (var i = 0; i < report.Findings.Count; i++)
        {
            var finding = report.Findings[i];
            var comma = i < report.Findings.Count - 1 ? "," : string.Empty;
            var spec = finding.SpecFile is null ? "null" : $"{{ \"file\": {J(finding.SpecFile)}, \"line\": {finding.SpecLine} }}";
            var code = finding.CodeFile is null ? "null" : $"{{ \"file\": {J(finding.CodeFile)}, \"line\": {finding.CodeLine} }}";
            builder.AppendLine(
                $"    {{ \"rule\": {J(finding.Rule)}, \"severity\": {J(finding.Severity)}, \"message\": {J(finding.Message)}, \"spec\": {spec}, \"code\": {code} }}{comma}");
        }

        builder.AppendLine("  ],");
        builder.AppendLine($"  \"errors\": {report.Errors},");
        builder.AppendLine($"  \"warnings\": {report.Warnings}");
        builder.Append("}");
        return builder.ToString();
    }

    private static void AppendFiles(StringBuilder builder, IReadOnlyList<DiffFile> files, Func<DiffFile, string?> area)
    {
        for (var i = 0; i < files.Count; i++)
        {
            var file = files[i];
            var comma = i < files.Count - 1 ? "," : string.Empty;
            var mappedArea = area(file);
            builder.AppendLine(
                $"    {{ \"path\": {J(file.Path)}, \"anchor\": {file.AddedLine}, \"new\": {file.IsNew.ToString().ToLowerInvariant()}, \"deleted\": {file.IsDeleted.ToString().ToLowerInvariant()}, \"area\": {(mappedArea is null ? "null" : J(mappedArea))} }}{comma}");
        }
    }

    private static string J(string value) => "\"" + System.Text.Json.JsonEncodedText.Encode(value) + "\"";
}
